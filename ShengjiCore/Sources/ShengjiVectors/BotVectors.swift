import ShengjiCore

/// bots.json: what the Swift bots (`Bot`) choose at every decision of many rounds, so the server's
/// TypeScript port of the bots can prove it chooses exactly the same cards.
///
/// Each round lists its deal (trump rank, dealer, deck order), how trump is decided (`mode`: "online"
/// is the server's turn-based bidding from `firstBidder`; "offline" is declaring while the cards are
/// dealt, as in the app) and who moves for each seat (`controllers`: a bot level, or "random", a
/// stand-in that makes random legal moves, failed throws included). Then one step per decision, in
/// three parts: `declaring`, `burying` and `playing`. A step names the deciding seat and the cards
/// the standard and the beginner bot choose from that seat's view (a declaration by its cards; none
/// for a pass); a random seat's step also has its move (`move`). An offline declaring step first
/// deals `deal` cards. Only choices are recorded: the TypeScript test replays each round with its own
/// engine (proven identical by the other vectors) to rebuild every view, and checks the `result`.
/// `deals` are more rounds that stop once the kitty is buried (no `playing`, no `result`): cheap
/// extra declaring and burying decisions.
enum BotVectors {
    enum Controller: String {
        case standard, beginner, random
    }

    static func make(online: Int, offline: Int, deals: Int) -> [(String, JSON)] {
        var rounds: [JSON] = []
        for index in 0..<online { rounds.append(entry(seed: UInt64(9000 + index), online: true)) }
        for index in 0..<offline { rounds.append(entry(seed: UInt64(9500 + index), online: false)) }
        var short: [JSON] = []
        for index in 0..<deals {
            short.append(entry(seed: UInt64(10_000 + index), online: index % 4 != 3, playOut: false))
        }
        return [
            ("format", .int(1)),
            ("about", .string("Generated by ShengjiVectors from the Swift bots. Do not edit.")),
            ("rounds", .array(rounds)),
            ("deals", .array(short)),
        ]
    }

    static func entry(seed: UInt64, online: Bool, playOut: Bool = true) -> JSON {
        var rand = Rand(seed)
        let rank = Rank.allCases[rand.below(Rank.allCases.count)]
        let dealer: Int? = rand.percent(25) ? nil : rand.below(4)
        let firstSeat = dealer ?? 0
        // Pair-rich deals keep tractors in play; joker-rich ones bring no trump declarations.
        let deckRoll = rand.below(100)
        let deck: [Card]
        if deckRoll < 20 {
            deck = RoundVectors.pairRichDeck(firstSeat: firstSeat, rand: &rand)
        } else if deckRoll < 35 {
            deck = jokerRichDeck(rank: rank, firstSeat: firstSeat, rand: &rand)
        } else {
            deck = rand.shuffled(Cards.all)
        }
        let controllers: [Controller] = (0..<4).map { _ in
            let roll = rand.below(100)
            return roll < 40 ? .standard : (roll < 65 ? .beginner : .random)
        }
        var round = Round(trumpRank: rank, dealer: dealer, deck: deck)
        let declaring = online
            ? bid(&round, firstBidder: firstSeat, controllers: controllers, rand: &rand)
            : declareWhileDealing(&round, controllers: controllers, rand: &rand)
        round.finishDealing()
        let burying = bury(&round, controllers: controllers, rand: &rand)
        var fields: [(String, JSON)] = [
            ("seed", .int(Int(seed))),
            ("mode", .string(online ? "online" : "offline")),
            ("trumpRank", json(rank)),
            ("dealer", json(dealer)),
        ]
        if online { fields.append(("firstBidder", .int(firstSeat))) }
        fields += [
            ("controllers", .array(controllers.map { .string($0.rawValue) })),
            ("deck", json(deck)),
            ("declaring", .array(declaring)),
            ("burying", burying),
        ]
        guard playOut else { return .object(fields) }
        var playing: [JSON] = []
        while round.phase == .playing, let player = round.turn {
            playing.append(play(&round, player: player, controllers: controllers, rand: &rand))
        }
        guard let result = round.result else { fatalError("bot round \(seed) did not finish") }
        fields += [("playing", .array(playing)), ("result", json(result))]
        return .object(fields)
    }

    /// A shuffled deck in which one seat is dealt all four jokers and a few trump-rank cards, so
    /// no-trump declarations (and no-trump rounds) come up often.
    static func jokerRichDeck(rank: Rank, firstSeat: Int, rand: inout Rand) -> [Card] {
        var deck = rand.shuffled(Cards.all)
        let seat = rand.below(4)
        let positions = (0..<100).filter { ($0 + firstSeat) % 4 == seat }
        let wanted = Cards.all.filter(\.isJoker) + rand.sample(Cards.all.filter { $0.rank == rank }, rand.between(0, 3))
        for (card, target) in zip(wanted, rand.sample(positions, wanted.count)) {
            guard let from = deck.firstIndex(of: card) else { fatalError("card missing from deck") }
            deck.swapAt(from, target)
        }
        return deck
    }

    static func cards(_ declaration: Declaration?) -> JSON { json(declaration?.cards ?? []) }

    /// The same declaration made by `player`.
    static func made(_ declaration: Declaration, by player: Int) -> Declaration {
        Declaration(player: player, cards: declaration.cards, suit: declaration.suit, strength: declaration.strength)
    }

    /// A random seat's declaration: often a joker pair when it has one, sometimes anything it may declare.
    static func randomDeclaration(_ available: [Declaration], rand: inout Rand) -> Declaration? {
        if let joker = available.last(where: { $0.suit == nil }), rand.percent(50) { return joker }
        return rand.percent(35) ? rand.pick(available) : nil
    }

    /// The declaring step of `seat` from `view`: both bots' choices, then the controller's move.
    static func declareStep(_ round: inout Round, seat: Int, view: SeatView, available: [Declaration],
                            controllers: [Controller], prefix: [(String, JSON)],
                            rand: inout Rand) -> (step: JSON, move: Declaration?) {
        let standard = Bot(seat: seat, level: .standard).declaration(view: view, available: available)
        let beginner = Bot(seat: seat, level: .beginner).declaration(view: view, available: available)
        var fields = prefix + [("seat", .int(seat)), ("standard", cards(standard)), ("beginner", cards(beginner))]
        let move: Declaration?
        switch controllers[seat] {
        case .standard: move = standard
        case .beginner: move = beginner
        case .random:
            move = randomDeclaration(available, rand: &rand)
            fields.append(("move", cards(move)))
        }
        if let declaration = move {
            do {
                try round.declare(made(declaration, by: seat))
            } catch {
                fatalError("declaration refused: \(error)")
            }
        }
        return (.object(fields), move)
    }

    /// The server's turn-based bidding (server/src/engine/round.ts `bid`): from `firstBidder`, each
    /// seat in turn declares or passes; three passes after a declaration, or four with none, end it.
    static func bid(_ round: inout Round, firstBidder: Int, controllers: [Controller], rand: inout Rand) -> [JSON] {
        round.dealAll()
        var steps: [JSON] = []
        var history: [SeatView.Bid] = []
        var turn = firstBidder
        var passes = 0
        while true {
            let available = round.availableDeclarations(for: turn).map { made($0, by: 0) }
            var view = round.seatView(for: turn)
            view.phase = .bidding
            let rotated = history.map { bid in
                SeatView.Bid(player: (bid.player - turn + 4) % 4,
                             declaration: bid.declaration.map { made($0, by: ($0.player - turn + 4) % 4) })
            }
            view.bidding = SeatView.Bidding(turn: 0, history: rotated, available: available)
            let result = declareStep(&round, seat: turn, view: view, available: available, controllers: controllers,
                                     prefix: [], rand: &rand)
            steps.append(result.step)
            history.append(SeatView.Bid(player: turn, declaration: result.move.map { made($0, by: turn) }))
            passes = result.move == nil ? passes + 1 : 0
            if round.declaration != nil ? passes >= 3 : passes >= 4 { break }
            turn = (turn + 1) % 4
        }
        return steps
    }

    /// Offline declaring, as in the app: the seat that just received a card may declare (here after
    /// every few cards), and once the deal is complete every seat has a last look.
    static func declareWhileDealing(_ round: inout Round, controllers: [Controller], rand: inout Rand) -> [JSON] {
        var steps: [JSON] = []
        func look(_ round: inout Round, seat: Int, prefix: [(String, JSON)], rand: inout Rand) -> JSON {
            let available = round.availableDeclarations(for: seat).map { made($0, by: 0) }
            let view = round.seatView(for: seat)
            return declareStep(&round, seat: seat, view: view, available: available,
                               controllers: controllers, prefix: prefix, rand: &rand).step
        }
        while !round.isDealingComplete {
            let count = min(round.undealt.count, rand.between(1, 8))
            var last = 0
            for _ in 0..<count {
                if let dealt = round.dealNext() { last = dealt.player }
            }
            steps.append(look(&round, seat: last, prefix: [("deal", .int(count))], rand: &rand))
        }
        for seat in [1, 2, 3, 0] { steps.append(look(&round, seat: seat, prefix: [], rand: &rand)) }
        return steps
    }

    static func bury(_ round: inout Round, controllers: [Controller], rand: inout Rand) -> JSON {
        guard let seat = round.dealer else { fatalError("no dealer after the declaring") }
        let view = round.seatView(for: seat)
        let standard = Bot(seat: seat, level: .standard).cardsToBury(view: view)?.cards ?? []
        let beginner = Bot(seat: seat, level: .beginner).cardsToBury(view: view)?.cards ?? []
        var fields: [(String, JSON)] = [("seat", .int(seat)), ("standard", json(standard)), ("beginner", json(beginner))]
        let move: [Card]
        switch controllers[seat] {
        case .standard: move = standard
        case .beginner: move = beginner
        case .random:
            let hand = round.hands[seat]
            let pointsFirst = hand.filter { $0.points > 0 } + rand.shuffled(hand.filter { $0.points == 0 })
            move = rand.percent(50) ? Array(pointsFirst.prefix(Round.kittySize)) : rand.sample(hand, Round.kittySize)
            fields.append(("move", json(move)))
        }
        do {
            try round.bury(move)
        } catch {
            fatalError("bury refused: \(error)")
        }
        return .object(fields)
    }

    static func play(_ round: inout Round, player: Int, controllers: [Controller], rand: inout Rand) -> JSON {
        let view = round.seatView(for: player)
        let standard = Bot(seat: player, level: .standard).decide(view: view)?.cards ?? []
        let beginner = Bot(seat: player, level: .beginner).decide(view: view)?.cards ?? []
        var fields: [(String, JSON)] = [("seat", .int(player)), ("standard", json(standard)), ("beginner", json(beginner))]
        let move: [Card]
        switch controllers[player] {
        case .standard: move = standard
        case .beginner: move = beginner
        case .random:
            let hand = round.hands[player]
            move = round.currentTrick.isEmpty
                ? Plays.randomLead(hand: hand, trump: round.trump, rand: &rand, throwPercent: 25)
                : Plays.follow(hand: hand, lead: round.currentLead, trump: round.trump, rand: &rand)
            fields.append(("move", json(move)))
        }
        do {
            try round.play(move, by: player)
        } catch {
            fatalError("play refused: \(error)")
        }
        return .object(fields)
    }
}
