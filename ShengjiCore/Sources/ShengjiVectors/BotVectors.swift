import ShengjiCore

/// bots.json: what the Swift bots (`Bot`) choose at every decision of many rounds, so the server's
/// TypeScript port of the bots can prove it chooses exactly the same cards.
///
/// Each round lists its deal (trump rank, dealer, deck order), how trump is decided (`mode`: "online"
/// is the server's turn-based bidding from `firstBidder`; "offline" is declaring while the cards are
/// dealt, as in the app) and who moves for each seat (`controllers`: a bot level, or "random", a
/// stand-in that makes random legal moves, failed throws included). Then one step per decision, in
/// three parts: `declaring`, `burying` and `playing`. A step names the deciding seat and the cards
/// the standard and the beginner bot choose from that seat's view (a declaration by its cards; none
/// for a pass); a random seat's step also has its move (`move`). An offline declaring step first
/// deals `deal` cards. Only choices are recorded: the TypeScript test replays each round with its own
/// engine (proven identical by the other vectors) to rebuild every view, and checks the `result`.
/// `deals` are more rounds that stop once the kitty is buried (no `playing`, no `result`): cheap
/// extra declaring and burying decisions. The last `ruffRounds` rounds are picked from more seeds:
/// only rounds in which the standard bot ruffs a throw, or ruffs a suit too short for the
/// opponents still to play to follow, are kept (both rare at random, and both have their own logic).
/// Then come rounds and deals at tables of 6 and 8 players (a `players` field): `bigOnline` and
/// `bigOffline` rounds after the others in `rounds`, `bigDeals` after the others in `deals`. Last come
/// tables of 5, 7 and 9 (Finding Friends): `oddOnline` and `oddOffline` rounds, `oddDeals` deals. Their
/// burying step also has the friends each bot calls (`standardCalls`, `beginnerCalls`) and a random
/// seat's calls (`moveCalls`).
enum BotVectors {
    enum Controller: String {
        case standard, beginner, random
    }

    static func make(online: Int, offline: Int, deals: Int, ruffRounds: Int,
                     bigOnline: Int, bigOffline: Int, bigDeals: Int,
                     oddOnline: Int, oddOffline: Int, oddDeals: Int) -> [(String, JSON)] {
        var rounds: [JSON] = []
        for index in 0..<online { rounds.append(entry(seed: UInt64(9000 + index), online: true)) }
        for index in 0..<offline { rounds.append(entry(seed: UInt64(9500 + index), online: false)) }
        var seed: UInt64 = 20_000
        var kept = 0
        while kept < ruffRounds {
            let candidate = round(seed: seed, online: seed % 4 != 3)
            if candidate.rareRuffs > 0 {
                rounds.append(candidate.json)
                kept += 1
            }
            seed += 1
        }
        for index in 0..<bigOnline {
            rounds.append(entry(seed: UInt64(30_000 + index), online: true, table: Cards.bigTables[index % 2]))
        }
        for index in 0..<bigOffline {
            rounds.append(entry(seed: UInt64(31_000 + index), online: false, table: Cards.bigTables[index % 2]))
        }
        for index in 0..<oddOnline {
            rounds.append(entry(seed: UInt64(33_000 + index), online: true, table: Cards.oddTables[index % 3]))
        }
        for index in 0..<oddOffline {
            rounds.append(entry(seed: UInt64(34_000 + index), online: false, table: Cards.oddTables[index % 3]))
        }
        var short: [JSON] = []
        for index in 0..<deals {
            short.append(entry(seed: UInt64(10_000 + index), online: index % 4 != 3, playOut: false))
        }
        for index in 0..<bigDeals {
            short.append(entry(seed: UInt64(32_000 + index), online: index % 4 != 3, playOut: false,
                               table: Cards.bigTables[index % 2]))
        }
        for index in 0..<oddDeals {
            short.append(entry(seed: UInt64(35_000 + index), online: index % 4 != 3, playOut: false,
                               table: Cards.oddTables[index % 3]))
        }
        return [
            ("format", .int(1)),
            ("about", .string("Generated by ShengjiVectors from the Swift bots. Do not edit.")),
            ("rounds", .array(rounds)),
            ("deals", .array(short)),
        ]
    }

    static func entry(seed: UInt64, online: Bool, playOut: Bool = true, table: TableSize = .four) -> JSON {
        round(seed: seed, online: online, playOut: playOut, table: table).json
    }

    /// The round of `seed`, and how many times the standard bot made a rare ruff in it (`isRareRuff`,
    /// two-deck rounds only).
    static func round(seed: UInt64, online: Bool, playOut: Bool = true,
                      table: TableSize = .four) -> (json: JSON, rareRuffs: Int) {
        var rand = Rand(seed)
        let n = table.players
        let rank = Rank.allCases[rand.below(Rank.allCases.count)]
        let dealer: Int? = rand.percent(25) ? nil : rand.below(n)
        let firstSeat = dealer ?? 0
        // Pair-rich deals keep tractors in play (with more decks, sets and tractors of sets);
        // joker-rich ones bring no trump declarations.
        let deckRoll = rand.below(100)
        let deck: [Card]
        if deckRoll < 20 {
            deck = table.isClassic ? RoundVectors.pairRichDeck(firstSeat: firstSeat, rand: &rand)
                : RoundVectors.setRichDeck(table: table, firstSeat: firstSeat, rand: &rand)
        } else if deckRoll < 35 {
            deck = jokerRichDeck(rank: rank, firstSeat: firstSeat, table: table, rand: &rand)
        } else {
            deck = rand.shuffled(Cards.deck(table.decks))
        }
        let controllers: [Controller] = (0..<n).map { _ in
            let roll = rand.below(100)
            return roll < 40 ? .standard : (roll < 65 ? .beginner : .random)
        }
        var round = Round(trumpRank: rank, dealer: dealer, deck: deck, table: table)
        let declaring = online
            ? bid(&round, firstBidder: firstSeat, controllers: controllers, rand: &rand)
            : declareWhileDealing(&round, controllers: controllers, rand: &rand)
        round.finishDealing()
        let burying = bury(&round, controllers: controllers, rand: &rand)
        var fields: [(String, JSON)] = table.isClassic ? [] : [("players", .int(n))]
        fields += [
            ("seed", .int(Int(seed))),
            ("mode", .string(online ? "online" : "offline")),
            ("trumpRank", json(rank)),
            ("dealer", json(dealer)),
        ]
        if online { fields.append(("firstBidder", .int(firstSeat))) }
        fields += [
            ("controllers", .array(controllers.map { .string($0.rawValue) })),
            ("deck", json(deck)),
            ("declaring", .array(declaring)),
            ("burying", burying),
        ]
        guard playOut else { return (.object(fields), 0) }
        var playing: [JSON] = []
        var rareRuffs = 0
        while round.phase == .playing, let player = round.turn {
            let step = play(&round, player: player, controllers: controllers, rand: &rand)
            playing.append(step.json)
            if step.rareRuff && table.isClassic { rareRuffs += 1 }
        }
        guard let result = round.result else { fatalError("bot round \(seed) did not finish") }
        fields += [("playing", .array(playing)), ("result", json(result))]
        return (.object(fields), rareRuffs)
    }

    /// The standard bot's `choice` from `view` trumps a plain-suit lead it is out of, and the lead is
    /// a throw, or so few cards of the suit are unseen that an opponent still to play is likely out of
    /// it too (the bot's `isRunningOut`).
    static func isRareRuff(view: SeatView, choice: [Card]) -> Bool {
        let trump = view.trump
        guard let lead = view.currentTrick.first?.cards, let group = Combos.group(of: lead, trump: trump),
              !group.isTrump, !view.hand.contains(where: { trump.group($0) == group }),
              !choice.isEmpty, choice.allSatisfy({ trump.isTrump($0) }) else { return false }
        if Rules.isThrow(lead, trump: trump) { return true }
        // Opponents (seats 1 and 3) still to play after the viewer (seat 0).
        let later = view.currentTrick.count < 3 ? Array(1...(3 - view.currentTrick.count)) : []
        let laterOpponents = later.filter { $0 % 2 == 1 }.count
        guard laterOpponents > 0 else { return false }
        var known = Set(view.hand.map(\.id))
        for card in view.playedCards { known.insert(card.id) }
        if view.phase == .playing, view.dealer == 0 { for card in view.kitty ?? [] { known.insert(card.id) } }
        let unseen = Cards.all.filter { !known.contains($0.id) && trump.group($0) == group }.count
        return unseen < max(1, lead.count * laterOpponents)
    }

    /// A shuffled deck in which one seat is dealt every joker and a few trump-rank cards, so
    /// no-trump declarations (and no-trump rounds) come up often.
    static func jokerRichDeck(rank: Rank, firstSeat: Int, table: TableSize = .four, rand: inout Rand) -> [Card] {
        let all = Cards.deck(table.decks)
        let n = table.players
        var deck = rand.shuffled(all)
        let seat = rand.below(n)
        let positions = (0..<(n * table.handSize)).filter { ($0 + firstSeat) % n == seat }
        let wanted = all.filter(\.isJoker) + rand.sample(all.filter { $0.rank == rank }, rand.between(0, 3))
        for (card, target) in zip(wanted, rand.sample(positions, wanted.count)) {
            guard let from = deck.firstIndex(of: card) else { fatalError("card missing from deck") }
            deck.swapAt(from, target)
        }
        return deck
    }

    static func cards(_ declaration: Declaration?) -> JSON { json(declaration?.cards ?? []) }

    /// The same declaration made by `player`.
    static func made(_ declaration: Declaration, by player: Int) -> Declaration {
        Declaration(player: player, cards: declaration.cards, suit: declaration.suit, strength: declaration.strength)
    }

    /// A random seat's declaration: often a joker pair when it has one, sometimes anything it may declare.
    static func randomDeclaration(_ available: [Declaration], rand: inout Rand) -> Declaration? {
        if let joker = available.last(where: { $0.suit == nil }), rand.percent(50) { return joker }
        return rand.percent(35) ? rand.pick(available) : nil
    }

    /// The declaring step of `seat` from `view`: both bots' choices, then the controller's move.
    static func declareStep(_ round: inout Round, seat: Int, view: SeatView, available: [Declaration],
                            controllers: [Controller], prefix: [(String, JSON)],
                            rand: inout Rand) -> (step: JSON, move: Declaration?) {
        let standard = Bot(seat: seat, level: .standard).declaration(view: view, available: available)
        let beginner = Bot(seat: seat, level: .beginner).declaration(view: view, available: available)
        var fields = prefix + [("seat", .int(seat)), ("standard", cards(standard)), ("beginner", cards(beginner))]
        let move: Declaration?
        switch controllers[seat] {
        case .standard: move = standard
        case .beginner: move = beginner
        case .random:
            move = randomDeclaration(available, rand: &rand)
            fields.append(("move", cards(move)))
        }
        if let declaration = move {
            do {
                try round.declare(made(declaration, by: seat))
            } catch {
                fatalError("declaration refused: \(error)")
            }
        }
        return (.object(fields), move)
    }

    /// The server's turn-based bidding (server/src/engine/round.ts `bid`): from `firstBidder`, each
    /// seat in turn declares or passes; a pass from every other player after a declaration (three
    /// with 4 players), or from everyone with none, ends it.
    static func bid(_ round: inout Round, firstBidder: Int, controllers: [Controller], rand: inout Rand) -> [JSON] {
        round.dealAll()
        let n = round.players
        var steps: [JSON] = []
        var history: [SeatView.Bid] = []
        var turn = firstBidder
        var passes = 0
        while true {
            let available = round.availableDeclarations(for: turn).map { made($0, by: 0) }
            var view = round.seatView(for: turn)
            view.phase = .bidding
            let rotated = history.map { bid in
                SeatView.Bid(player: (bid.player - turn + n) % n,
                             declaration: bid.declaration.map { made($0, by: ($0.player - turn + n) % n) })
            }
            view.bidding = SeatView.Bidding(turn: 0, history: rotated, available: available)
            let result = declareStep(&round, seat: turn, view: view, available: available, controllers: controllers,
                                     prefix: [], rand: &rand)
            steps.append(result.step)
            history.append(SeatView.Bid(player: turn, declaration: result.move.map { made($0, by: turn) }))
            passes = result.move == nil ? passes + 1 : 0
            if round.declaration != nil ? passes >= n - 1 : passes >= n { break }
            turn = (turn + 1) % n
        }
        return steps
    }

    /// Offline declaring, as in the app: the seat that just received a card may declare (here after
    /// every few cards), and once the deal is complete every seat has a last look.
    static func declareWhileDealing(_ round: inout Round, controllers: [Controller], rand: inout Rand) -> [JSON] {
        var steps: [JSON] = []
        func look(_ round: inout Round, seat: Int, prefix: [(String, JSON)], rand: inout Rand) -> JSON {
            let available = round.availableDeclarations(for: seat).map { made($0, by: 0) }
            let view = round.seatView(for: seat)
            return declareStep(&round, seat: seat, view: view, available: available,
                               controllers: controllers, prefix: prefix, rand: &rand).step
        }
        while !round.isDealingComplete {
            let count = min(round.undealt.count, rand.between(1, 8))
            var last = 0
            for _ in 0..<count {
                if let dealt = round.dealNext() { last = dealt.player }
            }
            steps.append(look(&round, seat: last, prefix: [("deal", .int(count))], rand: &rand))
        }
        for seat in Array(1..<round.players) + [0] { steps.append(look(&round, seat: seat, prefix: [], rand: &rand)) }
        return steps
    }

    static func bury(_ round: inout Round, controllers: [Controller], rand: inout Rand) -> JSON {
        guard let seat = round.dealer else { fatalError("no dealer after the declaring") }
        let view = round.seatView(for: seat)
        let standard = Bot(seat: seat, level: .standard).cardsToBury(view: view)?.cards ?? []
        let beginner = Bot(seat: seat, level: .beginner).cardsToBury(view: view)?.cards ?? []
        var fields: [(String, JSON)] = [("seat", .int(seat)), ("standard", json(standard)), ("beginner", json(beginner))]
        let move: [Card]
        switch controllers[seat] {
        case .standard: move = standard
        case .beginner: move = beginner
        case .random:
            let hand = round.hands[seat]
            let pointsFirst = hand.filter { $0.points > 0 } + rand.shuffled(hand.filter { $0.points == 0 })
            move = rand.percent(50) ? Array(pointsFirst.prefix(round.kittySize)) : rand.sample(hand, round.kittySize)
            fields.append(("move", json(move)))
        }
        var calls: [FriendCall] = []
        if round.isFindingFriends {
            let standardCalls = Bot(seat: seat, level: .standard).friendCalls(view: view, buried: standard)
            let beginnerCalls = Bot(seat: seat, level: .beginner).friendCalls(view: view, buried: beginner)
            fields += [("standardCalls", json(standardCalls)), ("beginnerCalls", json(beginnerCalls))]
            switch controllers[seat] {
            case .standard: calls = standardCalls
            case .beginner: calls = beginnerCalls
            case .random:
                calls = Cards.randomCalls(table: round.table, trumpRank: round.trumpRank, dealerHand: round.hands[seat],
                                          rand: &rand)
                fields.append(("moveCalls", json(calls)))
            }
        }
        do {
            try round.bury(move, calls: calls)
        } catch {
            fatalError("bury refused: \(error)")
        }
        return .object(fields)
    }

    static func play(_ round: inout Round, player: Int, controllers: [Controller],
                     rand: inout Rand) -> (json: JSON, rareRuff: Bool) {
        let view = round.seatView(for: player)
        let standard = Bot(seat: player, level: .standard).decide(view: view)?.cards ?? []
        let beginner = Bot(seat: player, level: .beginner).decide(view: view)?.cards ?? []
        var fields: [(String, JSON)] = [("seat", .int(player)), ("standard", json(standard)), ("beginner", json(beginner))]
        let move: [Card]
        switch controllers[player] {
        case .standard: move = standard
        case .beginner: move = beginner
        case .random:
            let hand = round.hands[player]
            if !round.currentTrick.isEmpty {
                move = Plays.follow(hand: hand, lead: round.currentLead, trump: round.trump, rand: &rand)
            } else if round.table.isClassic {
                move = Plays.randomLead(hand: hand, trump: round.trump, rand: &rand, throwPercent: 25)
            } else {
                let n = round.players
                let others = (1..<n).map { round.hands[(player + $0) % n] }
                move = Plays.setLead(hand: hand, others: others, trump: round.trump, rand: &rand)
            }
            fields.append(("move", json(move)))
        }
        do {
            try round.play(move, by: player)
        } catch {
            fatalError("play refused: \(error)")
        }
        return (.object(fields), isRareRuff(view: view, choice: standard))
    }
}
