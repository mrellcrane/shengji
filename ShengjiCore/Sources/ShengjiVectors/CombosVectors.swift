import ShengjiCore

/// combos.json: card, rank and suit tables, the trump order for every trump context, and random
/// card sets (biased to tricky cases) with their decomposition and shapes.
enum CombosVectors {
    static func make() -> [(String, JSON)] {
        [
            ("format", .int(1)),
            ("about", .string("Generated by ShengjiVectors from the Swift engine. Do not edit.")),
            ("suits", .array(Suit.allCases.map(suitEntry))),
            ("ranks", .array(Rank.allCases.map(rankEntry))),
            ("faces", .array(Cards.faces.map(faceEntry))),
            ("groups", .array(([.trump] + Suit.allCases.map { SuitGroup.plain($0) }).map(groupEntry))),
            ("shapes", .array(([.single, .pair] + (2...6).map { ComboShape.tractor($0) }).map(shapeEntry))),
            ("trumps", .array(allTrumps().map(trumpEntry))),
            ("cases", .array(cases(count: 1200))),
        ]
    }

    static func suitEntry(_ suit: Suit) -> JSON {
        .object([
            ("suit", .int(suit.rawValue)),
            ("symbol", .string(suit.symbol)),
            ("name", .string(suit.name)),
            ("singularName", .string(suit.singularName)),
            ("isRed", .bool(suit.isRed)),
        ])
    }

    static func rankEntry(_ rank: Rank) -> JSON {
        // advanced[steps + 1][cap index] for steps -1...5 and every cap.
        let advanced: [JSON] = (-1...5).map { steps in
            .array(Rank.allCases.map { cap in json(rank.advanced(by: steps, cap: cap)) })
        }
        return .object([
            ("rank", json(rank)),
            ("label", .string(rank.label)),
            ("name", .string(rank.name)),
            ("points", .int(rank.points)),
            ("advanced", .array(advanced)),
        ])
    }

    static func faceEntry(_ face: Face) -> JSON {
        .object([
            ("face", .int(face.index)),
            ("suit", json(face.suit)),
            ("rank", face.rank.map { json($0) } ?? .null),
            ("isJoker", .bool(face.isJoker)),
            ("points", .int(face.points)),
            ("description", .string(face.description)),
            ("longName", .string(face.longName)),
        ])
    }

    static func groupEntry(_ group: SuitGroup) -> JSON {
        .object([("group", json(group)), ("name", .string(group.name)), ("symbol", .string(group.symbol))])
    }

    static func shapeEntry(_ shape: ComboShape) -> JSON {
        .object([
            ("shape", json(shape)),
            ("name", .string(shape.name)),
            ("cardCount", .int(shape.cardCount)),
            ("pairCount", .int(shape.pairCount)),
        ])
    }

    static func allTrumps() -> [Trump] {
        Rank.allCases.flatMap { rank in ([nil] + Suit.allCases.map { Optional($0) }).map { Trump(rank: rank, suit: $0) } }
    }

    static func trumpEntry(_ trump: Trump) -> JSON {
        .object([
            ("trump", json(trump)),
            ("description", .string(trump.description)),
            ("summary", .string(trump.summary)),
            ("plainSuitOrder", .array(trump.plainSuitOrder.map { .int($0.rawValue) })),
            ("isTrump", .array(Cards.faces.map { .bool(trump.isTrump($0)) })),
            ("group", .array(Cards.faces.map { json(trump.group($0)) })),
            ("strength", .array(Cards.faces.map { .int(trump.strength($0)) })),
            ("sortKey", .array(Cards.all.prefix(54).map { .int(trump.sortKey($0)) })),
            ("highToLow", .array(trump.trumpFacesHighToLow.map { .int($0.index) })),
            ("sortedDeck", json(trump.sorted(Cards.all))),
        ])
    }

    // MARK: Card sets

    static func cases(count: Int) -> [JSON] {
        var rand = Rand(0xC0_4B05)
        return (0..<count).map { index in
            let (trump, cards) = cardSet(kind: index % 7, rand: &rand)
            return entry(trump: trump, cards: cards)
        }
    }

    /// Card sets of several kinds, all with distinct cards.
    static func cardSet(kind: Int, rand: inout Rand) -> (Trump, [Card]) {
        var trump = Cards.randomTrump(&rand)
        var pool = CardPool()
        var cards: [Card] = []
        switch kind {
        case 0:
            // A random hand.
            cards = rand.sample(Cards.all, rand.between(1, 30))
        case 1:
            // Many pairs in the trump group.
            let faces = Cards.faces(in: .trump, trump: trump)
            cards = pool.takeFaces(faces, count: rand.between(2, 24), pairPercent: 75, rand: &rand)
        case 2:
            // The trump-rank level: several off-suit rank pairs, the trump-suit rank, the top of the
            // trump suit and jokers (tractors across the skipped rank, equal rank cards).
            trump.suit = Suit.allCases[rand.below(4)]
            cards = pool.takeFaces(Cards.topTrumpFaces(trump), count: rand.between(4, 18), pairPercent: 85, rand: &rand)
            cards += pool.takeFaces(Cards.faces(in: .trump, trump: trump), count: rand.between(0, 6), pairPercent: 50,
                                    rand: &rand)
        case 3:
            // A plain suit around the trump rank: tractors that skip the rank (7799 when 8 is the rank).
            let suits = Suit.allCases.filter { $0 != trump.suit }
            let suit = suits[rand.below(suits.count)]
            let faces = Cards.faces(nearRankOf: trump, suit: suit, radius: rand.between(2, 5))
            cards = pool.takeFaces(faces, count: rand.between(2, 16), pairPercent: 80, rand: &rand)
            if rand.percent(30) {
                cards += pool.takeFaces([Face.regular(suit, trump.rank)], count: 2, pairPercent: 50, rand: &rand)
            }
        case 4:
            // No trump: rank pairs in several suits and joker pairs.
            trump.suit = nil
            cards = pool.takeFaces(Cards.topTrumpFaces(trump), count: rand.between(2, 12), pairPercent: 80, rand: &rand)
            cards += pool.takeFaces(Cards.faces, count: rand.between(0, 6), pairPercent: 40, rand: &rand)
        case 5:
            // One random group, pair-rich.
            let group = Cards.randomGroup(&rand, trump: trump)
            cards = pool.takeFaces(Cards.faces(in: group, trump: trump), count: rand.between(1, 20), pairPercent: 60,
                                   rand: &rand)
        default:
            // Two groups mixed together (decompose across groups; group(of:) is nil).
            let first = Cards.randomGroup(&rand, trump: trump)
            let second = Cards.randomGroup(&rand, trump: trump)
            cards = pool.takeFaces(Cards.faces(in: first, trump: trump), count: rand.between(1, 10), pairPercent: 60,
                                   rand: &rand)
            cards += pool.takeFaces(Cards.faces(in: second, trump: trump), count: rand.between(1, 10), pairPercent: 60,
                                    rand: &rand)
        }
        if cards.isEmpty { cards = [Cards.card(rand.below(108))] }
        return (trump, rand.shuffled(cards))
    }

    static func entry(trump: Trump, cards: [Card]) -> JSON {
        let longest = Combos.longestRun(in: cards, trump: trump)
        let tractorLengths = longest >= 2 ? Array(2...(longest + 1)) : [2]
        return .object([
            ("trump", json(trump)),
            ("cards", json(cards)),
            ("group", json(Combos.group(of: cards, trump: trump))),
            ("sorted", json(trump.sorted(cards))),
            ("decompose", .array(Combos.decompose(cards, trump: trump).map { json($0) })),
            ("shape", json(Combos.shape(of: cards, trump: trump))),
            ("isPair", .bool(Combos.isPair(cards))),
            ("pairs", .array(Combos.pairs(in: cards, trump: trump).map { json($0) })),
            ("pairCount", .int(Combos.pairCount(in: cards))),
            ("longestRun", .int(longest)),
            ("singles", json(Combos.components(of: .single, in: cards, trump: trump).map { $0.cards[0] })),
            // components(of: .tractor(length)) for each length: their cards and top strengths
            // (shape and group follow from the length and the cards).
            ("tractors", .array(tractorLengths.map { length in
                let components = Combos.components(of: .tractor(length), in: cards, trump: trump)
                return .object([
                    ("length", .int(length)),
                    ("cards", .array(components.map { json($0.cards) })),
                    ("tops", .array(components.map { .int($0.topStrength) })),
                ])
            })),
            ("isThrow", .bool(Rules.isThrow(cards, trump: trump))),
            ("kittyMultiplier", .int(Scoring.kittyMultiplier(lastLead: cards, trump: trump))),
        ])
    }
}
