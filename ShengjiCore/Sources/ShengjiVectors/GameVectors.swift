import ShengjiCore

/// games.json: the scoring table (`Scoring.outcome` for many point totals) and whole games:
/// `GameState` progression over many rounds (levels, next dealer, winner, `RoundSummary` and its
/// explanation text). Round results come from fully played random rounds or are synthesised
/// (consistent with the scoring rules) to reach every outcome quickly. After the two-deck ones come
/// outcomes for 3 and 4 decks (a `decks` field) and games at tables of 6 and 8 players (`players`).
/// Then outcomes for 5 decks, the short-handed bonus (`shortHanded`: Finding Friends), and games at
/// tables of 5, 7 and 9 players (Finding Friends: one level per seat, results with `declarers`).
enum GameVectors {
    static func make() -> [(String, JSON)] {
        var points = Array(stride(from: -10, through: 420, by: 5))
        points += [1, 4, 39, 41, 79, 81, 119, 121, 159, 161, 199, 201, 239, 241, 1000]
        var outcomes: [JSON] = points.map { value in
            let outcome = Scoring.outcome(defenderPoints: value)
            return .object([("points", .int(value)), ("outcome", json(outcome))])
        }
        for decks in [3, 4] {
            let step = Scoring.stepSize(decks: decks)
            var values = Array(stride(from: -10, through: 220 * decks, by: 5))
            for line in stride(from: step, through: 10 * step, by: step) { values += [line - 1, line + 1] }
            values += [1, 4, 1000]
            outcomes += values.map { value in
                let outcome = Scoring.outcome(defenderPoints: value, decks: decks)
                return .object([("decks", .int(decks)), ("points", .int(value)), ("outcome", json(outcome))])
            }
        }
        let step = Scoring.stepSize(decks: 5)
        var values = Array(stride(from: -10, through: 1100, by: 5))
        for line in stride(from: step, through: 10 * step, by: step) { values += [line - 1, line + 1] }
        outcomes += values.map { value in
            let outcome = Scoring.outcome(defenderPoints: value, decks: 5)
            return .object([("decks", .int(5)), ("points", .int(value)), ("outcome", json(outcome))])
        }
        for table in Cards.oddTables {
            for value in stride(from: 0, through: 50 * table.decks, by: 5 * table.decks) {
                let base = Scoring.outcome(defenderPoints: value, decks: table.decks)
                for declarers in 1...table.teamSize {
                    let outcome = Scoring.findingFriendsOutcome(base, declarers: declarers, fullSide: table.teamSize)
                    outcomes.append(.object([
                        ("decks", .int(table.decks)), ("points", .int(value)),
                        ("shortHanded", .object([("declarers", .int(declarers)), ("fullSide", .int(table.teamSize))])),
                        ("outcome", json(outcome)),
                    ]))
                }
            }
        }
        return [
            ("format", .int(1)),
            ("about", .string("Generated by ShengjiVectors from the Swift engine. Do not edit.")),
            ("outcomes", .array(outcomes)),
            ("games", .array(games() + bigGames() + oddGames())),
        ]
    }

    /// Games at tables of 5, 7 and 9 players (Finding Friends).
    static func oddGames() -> [JSON] {
        let specs: [(Rank, Rank, Source)] = [
            (.two, .ace, .synthetic), (.two, .ace, .synthetic), (.ten, .ace, .synthetic), (.two, .five, .played),
            (.nine, .jack, .played), (.two, .ace, .oddDealers), (.ace, .ace, .synthetic), (.five, .three, .synthetic),
            (.queen, .ace, .synthetic), (.two, .four, .played),
        ]
        var out: [JSON] = []
        for (index, spec) in specs.enumerated() {
            for (offset, table) in Cards.oddTables.enumerated() {
                out.append(game(settings: GameSettings(startRank: spec.0, targetRank: spec.1, table: table),
                                source: spec.2, seed: UInt64(21_000 + 3 * index + offset)))
            }
        }
        return out
    }

    /// Games at tables of 6 and 8 players: synthetic results through every band, played rounds and
    /// dealers outside the seats.
    static func bigGames() -> [JSON] {
        let specs: [(Rank, Rank, Source)] = [
            (.two, .ace, .synthetic), (.two, .ace, .synthetic), (.ten, .ace, .synthetic), (.two, .five, .played),
            (.nine, .jack, .played), (.two, .ace, .oddDealers), (.ace, .ace, .synthetic), (.five, .three, .synthetic),
        ]
        var out: [JSON] = []
        for (index, spec) in specs.enumerated() {
            for (offset, table) in Cards.bigTables.enumerated() {
                out.append(game(settings: GameSettings(startRank: spec.0, targetRank: spec.1, table: table),
                                source: spec.2, seed: UInt64(19_000 + 2 * index + offset)))
            }
        }
        return out
    }

    enum Source { case synthetic, played, oddDealers }

    static func games() -> [JSON] {
        let specs: [(Rank, Rank, Source)] = [
            (.two, .ace, .synthetic), (.two, .ace, .synthetic), (.two, .ace, .synthetic), (.two, .ace, .synthetic),
            (.two, .ace, .synthetic), (.two, .ace, .synthetic), (.two, .ace, .synthetic), (.two, .ace, .synthetic),
            (.two, .ace, .played), (.two, .five, .played), (.two, .four, .played), (.nine, .jack, .played),
            (.queen, .ace, .played), (.ten, .ace, .played),
            (.two, .two, .synthetic), (.ace, .ace, .synthetic), (.ten, .ace, .synthetic), (.king, .ace, .synthetic),
            (.five, .three, .synthetic), (.ace, .two, .synthetic), (.seven, .nine, .synthetic), (.two, .eight, .synthetic),
            (.jack, .king, .synthetic), (.three, .seven, .synthetic), (.four, .six, .synthetic), (.six, .ace, .synthetic),
            (.two, .ace, .oddDealers), (.eight, .queen, .oddDealers), (.two, .ace, .synthetic), (.two, .ace, .synthetic),
        ]
        return specs.enumerated().map { index, spec in
            game(settings: GameSettings(startRank: spec.0, targetRank: spec.1), source: spec.2,
                 seed: UInt64(9000 + index))
        }
    }

    static func game(settings: GameSettings, source: Source, seed: UInt64) -> JSON {
        var rand = Rand(seed)
        var state = GameState(settings: settings)
        var steps: [JSON] = []
        var extra = rand.between(0, 2)
        while steps.count < 80 {
            if state.winner != nil {
                if extra == 0 { break }
                extra -= 1
            }
            let trumpRank = state.nextTrumpRank
            let dealerBefore = state.nextDealer
            let result: RoundResult
            switch source {
            case .played:
                result = RoundVectors.playOut(trumpRank: trumpRank, dealer: dealerBefore, table: settings.table,
                                              rand: &rand)
            case .synthetic:
                result = synthetic(state, oddDealer: false, rand: &rand)
            case .oddDealers:
                result = synthetic(state, oddDealer: true, rand: &rand)
            }
            let summary = state.record(result)
            steps.append(.object([
                ("nextTrumpRank", json(trumpRank)),
                ("nextDealer", json(dealerBefore)),
                ("result", json(result)),
                ("summary", .object([
                    ("advancingTeam", json(summary.advancingTeam)),
                    ("levelsGained", .int(summary.levelsGained)),
                    ("levelsBefore", .array(summary.levelsBefore.map { json($0) })),
                    ("levelsAfter", .array(summary.levelsAfter.map { json($0) })),
                    ("nextDealer", .int(summary.nextDealer)),
                    ("gameWinner", json(summary.gameWinner)),
                    ("explanation", .string(summary.explanation)),
                ])),
                ("state", .object([
                    ("levels", .array(state.levels.map { json($0) })),
                    ("nextDealer", json(state.nextDealer)),
                    ("roundsPlayed", .int(state.roundsPlayed)),
                    ("winner", json(state.winner)),
                    ("nextTrumpRank", json(state.nextTrumpRank)),
                ])),
            ]))
        }
        let players: [(String, JSON)] = settings.table.isClassic ? [] : [("players", .int(settings.table.players))]
        return .object(players + [
            ("settings", .object([("startRank", json(settings.startRank)), ("targetRank", json(settings.targetRank))])),
            ("steps", .array(steps)),
        ])
    }

    /// A result consistent with the scoring rules, with defender points spread over every band (the
    /// bands scale with the table's decks).
    static func synthetic(_ state: GameState, oddDealer: Bool, rand: inout Rand) -> RoundResult {
        let table = state.settings.table
        if table.findsFriends { return syntheticFriends(state, oddDealer: oddDealer, rand: &rand) }
        let n = table.players
        let seat = state.nextDealer ?? rand.below(n)
        // Odd dealer values (outside the seats) must be normalised by `record`.
        let dealer = oddDealer && rand.percent(40) ? seat + n * rand.between(-3, 3) : seat
        let trump = Trump(rank: state.nextTrumpRank, suit: rand.percent(20) ? nil : Suit.allCases[rand.below(4)])
        let kitty = rand.sample(Cards.deck(table.decks), table.kittySize)
        let defendersWonLast = rand.percent(30)
        let multiplier = defendersWonLast ? [2, 4, 8, 12][rand.below(4)] : 0
        let step = Scoring.stepSize(decks: table.decks)
        let line = Scoring.takeoverThreshold(decks: table.decks)
        let bands = [(0, 0), (5, step - 5), (step, line - 5), (line, line + step - 5), (line + step, line + 2 * step - 5),
                     (line + 2 * step, line + 3 * step - 5), (line + 3 * step, line + 3 * step)]
        let band = bands[rand.below(bands.count)]
        let target = 5 * rand.between(band.0 / 5, band.1 / 5)
        let bonus = kitty.points * multiplier
        let trickPoints = min(table.totalPoints, max(0, target - bonus) / 5 * 5)
        let defenderPoints = trickPoints + bonus
        let lastWinner = defendersWonLast ? Seats.next(after: seat, players: n) : seat
        return RoundResult(
            dealer: dealer, declarerTeam: Seats.team(of: seat), trump: trump, trickPoints: trickPoints,
            kittyPoints: kitty.points, kittyMultiplier: multiplier, defenderPoints: defenderPoints,
            outcome: Scoring.outcome(defenderPoints: defenderPoints, decks: table.decks), kitty: kitty,
            lastTrickWinner: lastWinner)
    }
}

extension GameVectors {
    /// Finding Friends: a result consistent with the scoring rules. Each call is found by a random seat
    /// (maybe the dealer, maybe someone already found) or by nobody; the dealer's side is the dealer
    /// plus the friends found.
    static func syntheticFriends(_ state: GameState, oddDealer: Bool, rand: inout Rand) -> RoundResult {
        let table = state.settings.table
        let n = table.players
        let seat = state.nextDealer ?? rand.below(n)
        let dealer = oddDealer && rand.percent(40) ? seat + n * rand.between(-3, 3) : seat
        let trump = Trump(rank: state.nextTrumpRank, suit: rand.percent(20) ? nil : Suit.allCases[rand.below(4)])
        var calls = Cards.randomCalls(table: table, trumpRank: trump.rank, dealerHand: [], rand: &rand)
        for index in calls.indices where rand.percent(80) {
            calls[index].friend = rand.percent(10) ? seat : rand.below(n)
        }
        var declarers = [seat]
        for call in calls {
            if let friend = call.friend, !declarers.contains(friend) { declarers.append(friend) }
        }
        declarers.sort { Seats.normalized($0 - seat, players: n) < Seats.normalized($1 - seat, players: n) }
        let kitty = rand.sample(Cards.deck(table.decks), table.kittySize)
        let defendersWonLast = rand.percent(30)
        let multiplier = defendersWonLast ? [2, 4, 6, 8, 12][rand.below(5)] : 0
        let step = Scoring.stepSize(decks: table.decks)
        let line = Scoring.takeoverThreshold(decks: table.decks)
        let bands = [(0, 0), (5, step - 5), (step, line - 5), (line, line + step - 5), (line + step, line + 2 * step - 5),
                     (line + 2 * step, line + 3 * step - 5), (line + 3 * step, line + 3 * step)]
        let band = bands[rand.below(bands.count)]
        let target = 5 * rand.between(band.0 / 5, band.1 / 5)
        let bonus = kitty.points * multiplier
        let trickPoints = min(table.totalPoints, max(0, target - bonus) / 5 * 5)
        let defenderPoints = trickPoints + bonus
        let defenders = (1..<n).map { Seats.normalized(seat + $0, players: n) }.filter { !declarers.contains($0) }
        let lastWinner = defendersWonLast ? defenders.first ?? seat : seat
        let outcome = Scoring.findingFriendsOutcome(Scoring.outcome(defenderPoints: defenderPoints, decks: table.decks),
                                                    declarers: declarers.count, fullSide: table.teamSize)
        return RoundResult(
            dealer: dealer, declarerTeam: declarers.contains(0) ? 0 : 1, trump: trump, trickPoints: trickPoints,
            kittyPoints: kitty.points, kittyMultiplier: defendersWonLast && !defenders.isEmpty ? multiplier : 0,
            defenderPoints: defenderPoints, outcome: outcome, kitty: kitty, lastTrickWinner: lastWinner,
            declarers: declarers, friendCalls: calls)
    }
}
