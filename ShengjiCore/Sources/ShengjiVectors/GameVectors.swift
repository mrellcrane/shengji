import ShengjiCore

/// games.json: the scoring table (`Scoring.outcome` for many point totals) and whole games:
/// `GameState` progression over many rounds (levels, next dealer, winner, `RoundSummary` and its
/// explanation text). Round results come from fully played random rounds or are synthesised
/// (consistent with the scoring rules) to reach every outcome quickly.
enum GameVectors {
    static func make() -> [(String, JSON)] {
        var points = Array(stride(from: -10, through: 420, by: 5))
        points += [1, 4, 39, 41, 79, 81, 119, 121, 159, 161, 199, 201, 239, 241, 1000]
        let outcomes: [JSON] = points.map { value in
            let outcome = Scoring.outcome(defenderPoints: value)
            return .object([("points", .int(value)), ("outcome", json(outcome))])
        }
        return [
            ("format", .int(1)),
            ("about", .string("Generated by ShengjiVectors from the Swift engine. Do not edit.")),
            ("outcomes", .array(outcomes)),
            ("games", .array(games())),
        ]
    }

    enum Source { case synthetic, played, oddDealers }

    static func games() -> [JSON] {
        let specs: [(Rank, Rank, Source)] = [
            (.two, .ace, .synthetic), (.two, .ace, .synthetic), (.two, .ace, .synthetic), (.two, .ace, .synthetic),
            (.two, .ace, .synthetic), (.two, .ace, .synthetic), (.two, .ace, .synthetic), (.two, .ace, .synthetic),
            (.two, .ace, .played), (.two, .five, .played), (.two, .four, .played), (.nine, .jack, .played),
            (.queen, .ace, .played), (.ten, .ace, .played),
            (.two, .two, .synthetic), (.ace, .ace, .synthetic), (.ten, .ace, .synthetic), (.king, .ace, .synthetic),
            (.five, .three, .synthetic), (.ace, .two, .synthetic), (.seven, .nine, .synthetic), (.two, .eight, .synthetic),
            (.jack, .king, .synthetic), (.three, .seven, .synthetic), (.four, .six, .synthetic), (.six, .ace, .synthetic),
            (.two, .ace, .oddDealers), (.eight, .queen, .oddDealers), (.two, .ace, .synthetic), (.two, .ace, .synthetic),
        ]
        return specs.enumerated().map { index, spec in
            game(settings: GameSettings(startRank: spec.0, targetRank: spec.1), source: spec.2,
                 seed: UInt64(9000 + index))
        }
    }

    static func game(settings: GameSettings, source: Source, seed: UInt64) -> JSON {
        var rand = Rand(seed)
        var state = GameState(settings: settings)
        var steps: [JSON] = []
        var extra = rand.between(0, 2)
        while steps.count < 80 {
            if state.winner != nil {
                if extra == 0 { break }
                extra -= 1
            }
            let trumpRank = state.nextTrumpRank
            let dealerBefore = state.nextDealer
            let result: RoundResult
            switch source {
            case .played:
                result = RoundVectors.playOut(trumpRank: trumpRank, dealer: dealerBefore, rand: &rand)
            case .synthetic:
                result = synthetic(state, oddDealer: false, rand: &rand)
            case .oddDealers:
                result = synthetic(state, oddDealer: true, rand: &rand)
            }
            let summary = state.record(result)
            steps.append(.object([
                ("nextTrumpRank", json(trumpRank)),
                ("nextDealer", json(dealerBefore)),
                ("result", json(result)),
                ("summary", .object([
                    ("advancingTeam", json(summary.advancingTeam)),
                    ("levelsGained", .int(summary.levelsGained)),
                    ("levelsBefore", .array(summary.levelsBefore.map { json($0) })),
                    ("levelsAfter", .array(summary.levelsAfter.map { json($0) })),
                    ("nextDealer", .int(summary.nextDealer)),
                    ("gameWinner", json(summary.gameWinner)),
                    ("explanation", .string(summary.explanation)),
                ])),
                ("state", .object([
                    ("levels", .array(state.levels.map { json($0) })),
                    ("nextDealer", json(state.nextDealer)),
                    ("roundsPlayed", .int(state.roundsPlayed)),
                    ("winner", json(state.winner)),
                    ("nextTrumpRank", json(state.nextTrumpRank)),
                ])),
            ]))
        }
        return .object([
            ("settings", .object([("startRank", json(settings.startRank)), ("targetRank", json(settings.targetRank))])),
            ("steps", .array(steps)),
        ])
    }

    /// A result consistent with the scoring rules, with defender points spread over every band.
    static func synthetic(_ state: GameState, oddDealer: Bool, rand: inout Rand) -> RoundResult {
        let seat = state.nextDealer ?? rand.below(4)
        // Odd dealer values (outside 0...3) must be normalised by `record`.
        let dealer = oddDealer && rand.percent(40) ? seat + 4 * rand.between(-3, 3) : seat
        let trump = Trump(rank: state.nextTrumpRank, suit: rand.percent(20) ? nil : Suit.allCases[rand.below(4)])
        let kitty = rand.sample(Cards.all, 8)
        let defendersWonLast = rand.percent(30)
        let multiplier = defendersWonLast ? [2, 4, 8, 12][rand.below(4)] : 0
        let bands = [(0, 0), (5, 35), (40, 75), (80, 115), (120, 155), (160, 195), (200, 200)]
        let band = bands[rand.below(bands.count)]
        let target = 5 * rand.between(band.0 / 5, band.1 / 5)
        let bonus = kitty.points * multiplier
        let trickPoints = min(200, max(0, target - bonus) / 5 * 5)
        let defenderPoints = trickPoints + bonus
        let lastWinner = defendersWonLast ? Seats.next(after: seat) : seat
        return RoundResult(
            dealer: dealer, declarerTeam: Seats.team(of: seat), trump: trump, trickPoints: trickPoints,
            kittyPoints: kitty.points, kittyMultiplier: multiplier, defenderPoints: defenderPoints,
            outcome: Scoring.outcome(defenderPoints: defenderPoints), kitty: kitty, lastTrickWinner: lastWinner)
    }
}
