import ShengjiCore

/// rounds.json: full rounds driven through the public `Round` API. Each round lists its deck order,
/// dealer and trump rank, then every action with its expected result: dealing, declarations
/// (accepted or rejected, with `availableDeclarations` for every seat beforehand), state
/// snapshots, `finishDealing`, bury attempts, every play attempt (illegal ones with the
/// `RoundError` and its explanation; legal ones with the `PlayOutcome` and any finished trick),
/// and finally the `RoundResult`. After them, `bigCount` rounds at tables of 6 and 8 players (3 and
/// 4 decks, a `players` field; declarations of three and four cards, kitties of 6 and 8).
enum RoundVectors {
    static func make(count: Int, bigCount: Int) -> [(String, JSON)] {
        let classic = (0..<count).map { entry(seed: UInt64(5000 + $0)) }
        let big = (0..<bigCount).map { entry(seed: UInt64(15_000 + $0), table: Cards.bigTables[$0 % 2]) }
        return [
            ("format", .int(1)),
            ("about", .string("Generated by ShengjiVectors from the Swift engine. Do not edit.")),
            ("rounds", .array(classic + big)),
        ]
    }

    static func entry(seed: UInt64, table: TableSize = .four) -> JSON {
        var rand = Rand(seed)
        let n = table.players
        let kitty = table.kittySize
        let rank: Rank = rand.percent(25) ? .two : Rank.allCases[rand.below(13)]
        let dealer: Int? = rand.percent(25) ? nil : rand.below(n)
        // A third of the deals give every hand mostly pairs (with more decks: sets of two to four
        // cards): they stay in play to the end, so the last trick's lead is often a pair, set or
        // tractor (kitty multipliers 4, 6, 8, ...).
        let pairRich = rand.percent(33)
        let deck: [Card]
        if table.isClassic {
            deck = pairRich ? pairRichDeck(firstSeat: dealer ?? 0, rand: &rand) : rand.shuffled(Cards.all)
        } else {
            deck = pairRich ? setRichDeck(table: table, firstSeat: dealer ?? 0, rand: &rand)
                : rand.shuffled(Cards.deck(table.decks))
        }
        var round = Round(trumpRank: rank, dealer: dealer, deck: deck, table: table)
        var actions: [JSON] = []

        // Dealing, sometimes card by card with declarations along the way.
        if rand.percent(30) {
            while !round.isDealingComplete {
                let count = min(round.undealt.count, rand.between(1, 30))
                for _ in 0..<count { round.dealNext() }
                actions.append(.object([("op", .string("deal")), ("count", .int(count))]))
                if rand.percent(50) { actions.append(declareAttempt(&round, table: table, rand: &rand)) }
                if rand.percent(15) { actions.append(finishDealing(&round)) }
            }
        } else {
            round.dealAll()
            actions.append(.object([("op", .string("dealAll"))]))
        }
        actions.append(snapshot(round))

        // Declarations after the deal (none at all a quarter of the time: kitty flip).
        let declarations = rand.percent(25) ? 0 : rand.between(1, 6)
        for _ in 0..<declarations { actions.append(declareAttempt(&round, table: table, rand: &rand)) }
        if rand.percent(30) {
            actions.append(playAttempt(&round, player: rand.below(n), cards: [round.hands[0][0]]))
            actions.append(buryAttempt(&round, cards: Array(round.hands[0].prefix(kitty))))
        }

        actions.append(finishDealing(&round))
        actions.append(snapshot(round))
        guard let seat = round.dealer else { fatalError("no dealer after finishDealing") }

        // The window is closed: declaring and finishing again do nothing.
        if rand.percent(30) {
            actions.append(declareAttempt(&round, table: table, rand: &rand))
            actions.append(finishDealing(&round))
        }
        if rand.percent(20) {
            actions.append(playAttempt(&round, player: seat, cards: [round.hands[seat][0]]))
        }

        // Burying: a few illegal attempts, then a legal one.
        let hand = round.hands[seat]
        let outsider = round.hands[(seat + 1) % n][0]
        var buryAttempts: [[Card]] = []
        if rand.percent(30) { buryAttempts.append(rand.sample(hand, rand.percent(50) ? kitty - 1 : kitty + 1)) }
        if rand.percent(20) {
            let short = rand.sample(hand, kitty - 1)
            buryAttempts.append(short + [short[0]])
        }
        if rand.percent(20) { buryAttempts.append(rand.sample(hand, kitty - 1) + [outsider]) }
        if rand.percent(10) { buryAttempts.append([]) }
        // Point cards get buried a third of the time (they make the kitty bonus matter).
        let pointsFirst = hand.filter { $0.points > 0 } + rand.shuffled(hand.filter { $0.points == 0 })
        buryAttempts.append(rand.percent(35) ? Array(pointsFirst.prefix(kitty)) : rand.sample(hand, kitty))
        for cards in buryAttempts { actions.append(buryAttempt(&round, cards: cards)) }
        if rand.percent(20) { actions.append(buryAttempt(&round, cards: rand.sample(round.hands[seat], kitty))) }
        actions.append(snapshot(round))

        // Playing.
        var guardCount = 0
        while round.phase == .playing && guardCount < 1000 {
            guardCount += 1
            guard let player = round.turn else { break }
            if rand.percent(15), let attempt = illegalAttempt(round, player: player, rand: &rand) {
                actions.append(playAttempt(&round, player: attempt.player, cards: attempt.cards))
            }
            let cards = round.currentTrick.isEmpty
                ? lead(round, player: player, pairRich: pairRich, rand: &rand)
                : Plays.follow(hand: round.hands[player], lead: round.currentLead, trump: round.trump, rand: &rand)
            actions.append(playAttempt(&round, player: player, cards: cards))
        }
        guard round.phase == .finished, let result = round.result else { fatalError("round \(seed) did not finish") }
        actions.append(playAttempt(&round, player: round.leader, cards: []))
        actions.append(snapshot(round))

        let players: [(String, JSON)] = table.isClassic ? [] : [("players", .int(n))]
        return .object(players + [
            ("seed", .int(Int(seed))),
            ("trumpRank", json(rank)),
            ("dealer", json(dealer)),
            ("deck", json(deck)),
            ("actions", .array(actions)),
            ("result", json(result)),
        ])
    }

    /// A lead for a round in progress: mostly random (some throws fail), sometimes a throw that
    /// succeeds, and near the end often the biggest component, so the last trick's lead can be a
    /// pair or tractor (kitty multipliers above 2).
    static func lead(_ round: Round, player: Int, pairRich: Bool, rand: inout Rand) -> [Card] {
        let own = round.hands[player]
        let n = round.players
        let others = (1..<n).map { round.hands[(player + $0) % n] }
        if rand.percent(8), let sure = Plays.sureThrow(hand: own, others: others, trump: round.trump, rand: &rand) {
            return sure
        }
        if own.count <= 8 && Combos.group(of: own, trump: round.trump) != nil && rand.percent(60) {
            return own
        }
        if (own.count <= 8 || pairRich) && rand.percent(60) {
            let biggest = Cards.groups(own, trump: round.trump)
                .compactMap { Combos.decompose($0, trump: round.trump).first }
                .filter { $0.shape != .single }
            if let component = rand.pick(biggest) { return component.cards }
        }
        if !round.table.isClassic && rand.percent(30) {
            return Plays.setLead(hand: own, others: others, trump: round.trump, rand: &rand)
        }
        return Plays.randomLead(hand: own, trump: round.trump, rand: &rand, throwPercent: 20)
    }

    /// Bigger tables: a deck whose deal (from `firstSeat`) gives each seat mostly sets of two to four
    /// identical cards (every copy of a face goes to one seat), the rest at random.
    static func setRichDeck(table: TableSize, firstSeat: Int, rand: inout Rand) -> [Card] {
        let n = table.players
        let hand = table.handSize
        var hands = [[Card]](repeating: [], count: n)
        var rest: [Card] = []
        for face in rand.shuffled(Cards.faces) {
            let copies = (0..<table.decks).map { Cards.card(face.index + 54 * $0) }
            let seat = rand.below(n)
            if hands[seat].count + copies.count <= hand - 2 {
                hands[seat] += copies
            } else {
                rest += copies
            }
        }
        rest = rand.shuffled(rest)
        for seat in 0..<n {
            while hands[seat].count < hand, let card = rest.popLast() { hands[seat].append(card) }
            hands[seat] = rand.shuffled(hands[seat])
        }
        var deck: [Card] = []
        for index in 0..<(n * hand) {
            deck.append(hands[(firstSeat + index) % n][index / n])
        }
        return deck + rest
    }

    /// A deck whose deal (from `firstSeat`) gives each seat 12 pairs and one single.
    static func pairRichDeck(firstSeat: Int, rand: inout Rand) -> [Card] {
        let faces = rand.shuffled(Cards.faces)
        var hands: [[Card]] = []
        for seat in 0..<4 {
            let pairFaces = faces[(seat * 12)..<(seat * 12 + 12)]
            hands.append(rand.shuffled(pairFaces.flatMap { [Cards.card($0.index), Cards.card($0.index + 54)] }))
        }
        // The six faces left give each seat a single and make up the kitty.
        let rest = rand.shuffled(faces[48...].flatMap { [Cards.card($0.index), Cards.card($0.index + 54)] })
        for seat in 0..<4 { hands[seat].insert(rest[seat], at: rand.below(25)) }
        var deck: [Card] = []
        for index in 0..<100 {
            deck.append(hands[(firstSeat + index) % 4][index / 4])
        }
        return deck + rest[4...]
    }

    // MARK: Actions

    static func errorFields(_ error: RoundError?) -> [(String, JSON)] {
        [("error", error.map { json($0) } ?? .null), ("explanation", error.map { .string($0.explanation) } ?? .null)]
    }

    /// Records the state fields every engine must agree on.
    static func snapshot(_ round: Round) -> JSON {
        .object([
            ("op", .string("check")),
            ("phase", .string(round.phase.rawValue)),
            ("dealer", json(round.dealer)),
            ("leader", .int(round.leader)),
            ("turn", json(round.turn)),
            ("declarerTeam", json(round.declarerTeam)),
            ("trump", json(round.trump)),
            ("trumpFromKitty", json(round.trumpFromKitty)),
            ("declaration", round.declaration.map { json($0) } ?? .null),
            ("declarationCount", .int(round.declarationHistory.count)),
            ("hands", json(round.hands)),
            ("kitty", json(round.kitty)),
            ("undealtCount", .int(round.undealt.count)),
            ("nextToReceive", .int(round.nextToReceive)),
            ("trickCount", .int(round.tricks.count)),
            ("defenderTrickPoints", .int(round.defenderTrickPoints)),
            ("playedCount", .int(round.playedCards.count)),
        ])
    }

    static func finishDealing(_ round: inout Round) -> JSON {
        round.finishDealing()
        return .object([
            ("op", .string("finishDealing")),
            ("phase", .string(round.phase.rawValue)),
            ("dealer", json(round.dealer)),
            ("trump", json(round.trump)),
            ("trumpFromKitty", json(round.trumpFromKitty)),
        ])
    }

    static func declareAttempt(_ round: inout Round, table: TableSize = .four, rand: inout Rand) -> JSON {
        let available = (0..<table.players).map { round.availableDeclarations(for: $0) }
        let options = available.flatMap { $0 }
        let declaration: Declaration
        if rand.percent(55), let option = rand.pick(options) {
            declaration = option
        } else {
            declaration = doubtfulDeclaration(round, table: table, rand: &rand)
        }
        var error: RoundError?
        do {
            try round.declare(declaration)
        } catch let failure as RoundError {
            error = failure
        } catch {
            fatalError("unexpected error \(error)")
        }
        return .object([
            ("op", .string("declare")),
            ("available", .array(available.map { .array($0.map { json($0) }) })),
            ("declaration", json(declaration)),
            ("description", .string(table.isClassic ? declaration.description
                : declaration.description(players: table.players))),
        ] + errorFields(error))
    }

    /// A declaration that is often (not always) invalid: equal strength, own suit switch, a single
    /// claimed as a pair, someone else's cards, jokers with a suit, a bad seat. With more decks also
    /// three or four cards claimed with the wrong strength or cards.
    static func doubtfulDeclaration(_ round: Round, table: TableSize = .four, rand: inout Rand) -> Declaration {
        let n = table.players
        let player = rand.below(n)
        let hand = Cards.byID(round.hands[player])
        let rank = round.trumpRank
        let rankCards = hand.filter { $0.rank == rank }
        let everywhere = Cards.byID(round.hands.flatMap { $0 })
        switch rand.below(table.isClassic ? 7 : 9) {
        case 0:
            if let card = rand.pick(rankCards) { return Declaration(player: player, cards: [card], suit: card.suit, strength: 1) }
        case 1:
            if let card = rand.pick(rankCards) { return Declaration(player: player, cards: [card], suit: card.suit, strength: 2) }
        case 2:
            let foreign = everywhere.filter { $0.rank == rank && !hand.contains($0) }
            if let card = rand.pick(foreign) { return Declaration(player: player, cards: [card], suit: card.suit, strength: 1) }
        case 3:
            let jokers = hand.filter { $0.isJoker }
            if jokers.count >= 2 {
                return Declaration(player: player, cards: Array(jokers.prefix(2)), suit: Suit.allCases[rand.below(4)],
                                   strength: rand.between(3, 4))
            }
        case 4:
            if let card = rand.pick(rankCards) {
                return Declaration(player: rand.percent(50) ? n : -1, cards: [card], suit: card.suit, strength: 1)
            }
        case 5:
            // Right cards, wrong suit or strength.
            if let card = rand.pick(rankCards), let suit = card.suit {
                let other = Suit.allCases[(suit.rawValue + 1 + rand.below(3)) % 4]
                return Declaration(player: player, cards: [card], suit: rand.percent(50) ? other : nil,
                                   strength: rand.between(0, table.isClassic ? 5 : 10))
            }
        case 7:
            // Several rank cards of one suit (or jokers) claimed with a strength near the right one.
            let groups = Dictionary(grouping: hand.filter { $0.rank == rank || $0.isJoker }, by: \.face.index)
            if let face = rand.pick(groups.keys.sorted()), let cards = groups[face], cards.count >= 2 {
                let count = rand.between(2, cards.count)
                let suit = cards[0].suit
                return Declaration(player: player, cards: Array(cards.prefix(count)), suit: suit,
                                   strength: max(0, 3 * count - 4 + rand.between(-1, 2)))
            }
        case 8:
            // The same card twice.
            if let card = rand.pick(rankCards) {
                return Declaration(player: player, cards: [card, card, card], suit: card.suit, strength: 5)
            }
        default:
            break
        }
        // Someone else's available declaration claimed by this player, or a plain single.
        let theirs = (0..<n).flatMap { round.availableDeclarations(for: $0) }
        if let option = rand.pick(theirs) {
            return Declaration(player: player, cards: option.cards, suit: option.suit, strength: option.strength)
        }
        let card = rand.pick(hand) ?? Cards.card(0)
        return Declaration(player: player, cards: [card], suit: card.suit, strength: 1)
    }

    static func buryAttempt(_ round: inout Round, cards: [Card]) -> JSON {
        var error: RoundError?
        do {
            try round.bury(cards)
        } catch let failure as RoundError {
            error = failure
        } catch {
            fatalError("unexpected error \(error)")
        }
        return .object([("op", .string("bury")), ("cards", json(cards))] + errorFields(error))
    }

    static func playAttempt(_ round: inout Round, player: Int, cards: [Card]) -> JSON {
        let tricksBefore = round.tricks.count
        var fields: [(String, JSON)] = [("op", .string("play")), ("player", .int(player)), ("cards", json(cards))]
        do {
            // A plain successful play has no "outcome" field (it means .played); a failed throw has one.
            let outcome = try round.play(cards, by: player)
            if outcome != .played { fields.append(("outcome", json(outcome))) }
            // The finished trick's plays are the plays just replayed, so only its result is recorded.
            if round.tricks.count > tricksBefore, let trick = round.tricks.last {
                fields.append(("trick", .object([("winner", .int(trick.winner)), ("points", .int(trick.points))])))
            }
        } catch let failure as RoundError {
            fields += errorFields(failure)
        } catch {
            fatalError("unexpected error \(error)")
        }
        return .object(fields)
    }

    /// An attempt that `legalityError` rejects, or nil if the random attempt happened to be legal.
    static func illegalAttempt(_ round: Round, player: Int, rand: inout Rand) -> (player: Int, cards: [Card])? {
        let hand = round.hands[player]
        let lead = round.currentLead
        var attempt: (player: Int, cards: [Card])
        let n = round.players
        if !lead.isEmpty && rand.percent(40) {
            // Follow attempts that break suit or structure obligations.
            let elsewhere = (1..<n).flatMap { round.hands[(player + $0) % n] }
            let options = Plays.randomAttempts(hand: hand, lead: lead, trump: round.trump, elsewhere: elsewhere,
                                               rand: &rand)
            if let cards = rand.pick(options.filter {
                round.legalityError(for: $0, by: player) != nil
            }) {
                return (player, cards)
            }
        }
        switch rand.below(5) {
        case 0:
            let other = (player + 1 + rand.below(n - 1)) % n
            attempt = (other, rand.sample(round.hands[other], max(1, lead.count)))
        case 1:
            let count = lead.isEmpty ? rand.between(2, 5) : lead.count + (lead.count > 1 && rand.percent(50) ? -1 : 1)
            attempt = (player, rand.sample(hand, count))
        case 2:
            let groups = Cards.groups(hand, trump: round.trump)
            if lead.isEmpty && groups.count >= 2 && rand.percent(70) {
                attempt = (player, [groups[0][0], groups[groups.count - 1][0]])
            } else {
                attempt = (player, lead.isEmpty ? [] : rand.sample(hand, lead.count))
            }
        case 3:
            let others = (1..<n).flatMap { round.hands[(player + $0) % n] }
            guard let stranger = rand.pick(others) else { return nil }
            attempt = (player, rand.sample(hand, max(1, lead.count) - 1) + [stranger])
        default:
            attempt = (player, rand.sample(hand, max(1, lead.count)))
        }
        return round.legalityError(for: attempt.cards, by: attempt.player) == nil ? nil : attempt
    }

    // MARK: Whole rounds for games.json

    /// Plays a round with random legal moves and returns its result.
    static func playOut(trumpRank: Rank, dealer: Int?, table: TableSize = .four, rand: inout Rand) -> RoundResult {
        var round = Round(trumpRank: trumpRank, dealer: dealer, deck: rand.shuffled(Cards.deck(table.decks)), table: table)
        round.dealAll()
        for _ in 0..<rand.between(0, 4) {
            let seat = rand.below(table.players)
            if let option = rand.pick(round.availableDeclarations(for: seat)) { try? round.declare(option) }
        }
        round.finishDealing()
        guard let seat = round.dealer else { fatalError("no dealer") }
        do {
            try round.bury(rand.sample(round.hands[seat], table.kittySize))
            while round.phase == .playing, let player = round.turn {
                let own = round.hands[player]
                let cards = round.currentTrick.isEmpty
                    ? Plays.randomLead(hand: own, trump: round.trump, rand: &rand, throwPercent: 20)
                    : Plays.follow(hand: own, lead: round.currentLead, trump: round.trump, rand: &rand)
                try round.play(cards, by: player)
            }
        } catch {
            fatalError("random round failed: \(error)")
        }
        guard let result = round.result else { fatalError("round did not finish") }
        return result
    }
}
