import Foundation
import ShengjiCore

/// views.json: the per-seat view the online server sends (`Round.seatView(for:players:game:)`),
/// for all four seats at many points of many rounds: just after the deal closes (burying), right
/// after burying, in the middle of play (often mid-trick), finished but not yet recorded, and
/// finished and recorded (the game then holds the round's summary, sometimes the game winner).
///
/// Each case carries its inputs in the TypeScript engine's field names (players, the `GameState`
/// with only its last history entry, which is all a view reads, and the `Round`) and the four
/// views exactly as the Swift `SeatView` Codable encodes them (absent optionals are left out).
enum ViewVectors {
    static func make(games: Int) -> [(String, JSON)] {
        var cases: [JSON] = []
        for index in 0..<games {
            cases += game(seed: UInt64(7000 + index))
        }
        return [
            ("format", .int(1)),
            ("about", .string("Generated by ShengjiVectors from the Swift engine. Do not edit.")),
            ("cases", .array(cases)),
        ]
    }

    static let humanNames = ["Mei", "Lin", "Sam", "Ana", "小明", "Jo", "Priya", "Tom"]
    static let botNames = ["Panda Bot", "Tiger Bot", "Crane Bot", "Dragon Bot"]

    static func players(_ rand: inout Rand) -> [SeatView.Player] {
        let names = rand.shuffled(humanNames)
        return (0..<4).map { seat in
            if seat == 0 || rand.percent(55) {
                return SeatView.Player(name: names[seat], isBot: false, userID: "u_test\(seat)\(rand.below(1000))")
            }
            return SeatView.Player(name: botNames[seat], isBot: true, userID: nil)
        }
    }

    static func game(seed: UInt64) -> [JSON] {
        var rand = Rand(seed)
        let starts: [Rank] = [.two, .two, .five, .ten, .king, .ace]
        let start = starts[rand.below(starts.count)]
        // Low targets end games quickly, so finished games and capped levels show up.
        let target = rand.percent(40) ? start.advanced(by: rand.between(0, 1)) : .ace
        var state = GameState(settings: GameSettings(startRank: start, targetRank: target))
        let seats = players(&rand)
        var out: [JSON] = []

        // A few recorded rounds first (synthetic results), so views carry a previous round's summary.
        for _ in 0..<rand.between(0, 3) where state.winner == nil {
            state.record(GameVectors.synthetic(state, oddDealer: false, rand: &rand))
        }

        for _ in 0..<2 {
            var round = Round(trumpRank: state.nextTrumpRank, dealer: state.nextDealer, deck: rand.shuffled(Cards.all))
            round.dealAll()
            // No declaration a quarter of the time: the kitty flip fixes trump (`trumpFromKitty`).
            if !rand.percent(25) {
                for _ in 0..<rand.between(1, 4) {
                    let seat = rand.below(4)
                    if let option = rand.pick(round.availableDeclarations(for: seat)) { try? round.declare(option) }
                }
            }
            round.finishDealing()
            guard let dealer = round.dealer else { fatalError("no dealer after finishDealing") }
            if rand.percent(70) { out.append(entry("burying", seats, state, round)) }

            let hand = round.hands[dealer]
            let pointsFirst = hand.filter { $0.points > 0 } + rand.shuffled(hand.filter { $0.points == 0 })
            do {
                try round.bury(rand.percent(35) ? Array(pointsFirst.prefix(8)) : rand.sample(hand, 8))
            } catch {
                fatalError("bury failed: \(error)")
            }
            if rand.percent(40) { out.append(entry("buried", seats, state, round)) }

            let stopAt = rand.between(1, 99)
            var plays = 0
            while round.phase == .playing, let player = round.turn {
                if plays == stopAt { out.append(entry("playing", seats, state, round)) }
                let own = round.hands[player]
                let cards = round.currentTrick.isEmpty
                    ? Plays.randomLead(hand: own, trump: round.trump, rand: &rand, throwPercent: 20)
                    : Plays.follow(hand: own, lead: round.currentLead, trump: round.trump, rand: &rand)
                do {
                    try round.play(cards, by: player)
                } catch {
                    fatalError("play failed: \(error)")
                }
                plays += 1
            }
            guard let result = round.result else { fatalError("round did not finish") }
            if rand.percent(30) { out.append(entry("finished", seats, state, round)) }
            state.record(result)
            out.append(entry("recorded", seats, state, round))
            if state.winner != nil { break }
        }
        return out
    }

    static func entry(_ label: String, _ players: [SeatView.Player], _ game: GameState, _ round: Round) -> JSON {
        .object([
            ("label", .string(label)),
            ("players", .array(players.map { player in
                .object([
                    ("name", .string(player.name)),
                    ("isBot", .bool(player.isBot)),
                    ("userID", player.userID.map { .string($0) } ?? .null),
                ])
            })),
            ("game", json(game)),
            ("round", json(round)),
            ("views", .array((0..<4).map { codable(round.seatView(for: $0, players: players, game: game)) })),
        ])
    }

    // MARK: Inputs in the TypeScript engine's field names

    static func json(_ summary: RoundSummary) -> JSON {
        .object([
            ("result", ShengjiVectors.json(summary.result)),
            ("advancingTeam", ShengjiVectors.json(summary.advancingTeam)),
            ("levelsGained", .int(summary.levelsGained)),
            ("levelsBefore", .array(summary.levelsBefore.map { ShengjiVectors.json($0) })),
            ("levelsAfter", .array(summary.levelsAfter.map { ShengjiVectors.json($0) })),
            ("nextDealer", .int(summary.nextDealer)),
            ("gameWinner", ShengjiVectors.json(summary.gameWinner)),
            ("explanation", .string(summary.explanation)),
        ])
    }

    /// The game with only its last history entry (all a view reads).
    static func json(_ game: GameState) -> JSON {
        .object([
            ("settings", .object([
                ("startRank", ShengjiVectors.json(game.settings.startRank)),
                ("targetRank", ShengjiVectors.json(game.settings.targetRank)),
            ])),
            ("levels", .array(game.levels.map { ShengjiVectors.json($0) })),
            ("nextDealer", ShengjiVectors.json(game.nextDealer)),
            ("roundsPlayed", .int(game.roundsPlayed)),
            ("winner", ShengjiVectors.json(game.winner)),
            ("history", .array(game.history.suffix(1).map { json($0) })),
        ])
    }

    static func json(_ round: Round) -> JSON {
        .object([
            ("trumpRank", ShengjiVectors.json(round.trumpRank)),
            ("dealer", ShengjiVectors.json(round.dealer)),
            ("phase", .string(round.phase.rawValue)),
            ("hands", ShengjiVectors.json(round.hands)),
            ("undealt", ShengjiVectors.json(round.undealt)),
            ("kitty", ShengjiVectors.json(round.kitty)),
            ("declaration", round.declaration.map { ShengjiVectors.json($0) } ?? .null),
            ("declarationHistory", .array(round.declarationHistory.map { ShengjiVectors.json($0) })),
            ("trump", ShengjiVectors.json(round.trump)),
            ("nextToReceive", .int(round.nextToReceive)),
            ("currentTrick", .array(round.currentTrick.map { ShengjiVectors.json($0) })),
            ("tricks", .array(round.tricks.map { ShengjiVectors.json($0) })),
            ("leader", .int(round.leader)),
            ("defenderTrickPoints", .int(round.defenderTrickPoints)),
            ("trumpFromKitty", ShengjiVectors.json(round.trumpFromKitty)),
            ("result", round.result.map { ShengjiVectors.json($0) } ?? .null),
            ("bidding", .null),
        ])
    }

    // MARK: The view as the Swift Codable writes it

    /// `value` encoded by `JSONEncoder` (the wire format), read back into the ordered JSON value so
    /// the file is written byte-for-byte deterministically.
    static func codable<T: Encodable>(_ value: T) -> JSON {
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.sortedKeys]
        do {
            var parser = JSONParser(bytes: Array(try encoder.encode(value)))
            return try parser.document()
        } catch {
            fatalError("cannot encode \(T.self): \(error)")
        }
    }
}

/// A strict reader for the JSON that `JSONEncoder` writes (integers only, no floats).
struct JSONParser {
    struct Failure: Error, CustomStringConvertible {
        var description: String
    }

    private let bytes: [UInt8]
    private var index = 0

    init(bytes: [UInt8]) { self.bytes = bytes }

    mutating func document() throws -> JSON {
        let value = try parseValue()
        skipSpace()
        guard index == bytes.count else { throw Failure(description: "trailing bytes at \(index)") }
        return value
    }

    private mutating func skipSpace() {
        while index < bytes.count, [0x20, 0x0A, 0x0D, 0x09].contains(bytes[index]) { index += 1 }
    }

    private mutating func expect(_ literal: String) throws {
        for byte in literal.utf8 {
            guard index < bytes.count, bytes[index] == byte else { throw Failure(description: "expected \(literal)") }
            index += 1
        }
    }

    private mutating func parseValue() throws -> JSON {
        skipSpace()
        guard index < bytes.count else { throw Failure(description: "unexpected end") }
        switch bytes[index] {
        case UInt8(ascii: "{"):
            index += 1
            var fields: [(String, JSON)] = []
            skipSpace()
            if index < bytes.count, bytes[index] == UInt8(ascii: "}") {
                index += 1
                return .object(fields)
            }
            while true {
                skipSpace()
                let key = try parseString()
                skipSpace()
                try expect(":")
                fields.append((key, try parseValue()))
                skipSpace()
                guard index < bytes.count else { throw Failure(description: "unterminated object") }
                if bytes[index] == UInt8(ascii: ",") { index += 1; continue }
                try expect("}")
                return .object(fields)
            }
        case UInt8(ascii: "["):
            index += 1
            var items: [JSON] = []
            skipSpace()
            if index < bytes.count, bytes[index] == UInt8(ascii: "]") {
                index += 1
                return .array(items)
            }
            while true {
                items.append(try parseValue())
                skipSpace()
                guard index < bytes.count else { throw Failure(description: "unterminated array") }
                if bytes[index] == UInt8(ascii: ",") { index += 1; continue }
                try expect("]")
                return .array(items)
            }
        case UInt8(ascii: "\""):
            return .string(try parseString())
        case UInt8(ascii: "t"):
            try expect("true")
            return .bool(true)
        case UInt8(ascii: "f"):
            try expect("false")
            return .bool(false)
        case UInt8(ascii: "n"):
            try expect("null")
            return .null
        default:
            return .int(try parseInt())
        }
    }

    private mutating func parseInt() throws -> Int {
        let start = index
        if index < bytes.count, bytes[index] == UInt8(ascii: "-") { index += 1 }
        while index < bytes.count, bytes[index] >= UInt8(ascii: "0"), bytes[index] <= UInt8(ascii: "9") { index += 1 }
        guard let text = String(bytes: bytes[start..<index], encoding: .utf8), let value = Int(text) else {
            throw Failure(description: "bad number at \(start)")
        }
        if index < bytes.count, [UInt8(ascii: "."), UInt8(ascii: "e"), UInt8(ascii: "E")].contains(bytes[index]) {
            throw Failure(description: "non-integer number at \(start)")
        }
        return value
    }

    private mutating func parseHex4() throws -> UInt32 {
        guard index + 4 <= bytes.count, let text = String(bytes: bytes[index..<(index + 4)], encoding: .utf8),
              let value = UInt32(text, radix: 16) else { throw Failure(description: "bad \\u escape") }
        index += 4
        return value
    }

    private mutating func parseString() throws -> String {
        try expect("\"")
        var raw: [UInt8] = []
        while true {
            guard index < bytes.count else { throw Failure(description: "unterminated string") }
            let byte = bytes[index]
            index += 1
            if byte == UInt8(ascii: "\"") { break }
            if byte != UInt8(ascii: "\\") {
                raw.append(byte)
                continue
            }
            guard index < bytes.count else { throw Failure(description: "bad escape") }
            let escape = bytes[index]
            index += 1
            switch escape {
            case UInt8(ascii: "\""): raw.append(0x22)
            case UInt8(ascii: "\\"): raw.append(0x5C)
            case UInt8(ascii: "/"): raw.append(0x2F)
            case UInt8(ascii: "b"): raw.append(0x08)
            case UInt8(ascii: "f"): raw.append(0x0C)
            case UInt8(ascii: "n"): raw.append(0x0A)
            case UInt8(ascii: "r"): raw.append(0x0D)
            case UInt8(ascii: "t"): raw.append(0x09)
            case UInt8(ascii: "u"):
                var code = try parseHex4()
                if (0xD800...0xDBFF).contains(code) {
                    try expect("\\u")
                    let low = try parseHex4()
                    code = 0x10000 + ((code - 0xD800) << 10) + (low - 0xDC00)
                }
                guard let scalar = Unicode.Scalar(code) else { throw Failure(description: "bad scalar") }
                raw += Array(String(Character(scalar)).utf8)
            default:
                throw Failure(description: "bad escape")
            }
        }
        guard let text = String(bytes: raw, encoding: .utf8) else { throw Failure(description: "bad UTF-8") }
        return text
    }
}
