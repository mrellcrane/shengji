import ShengjiCore

/// edges.json: targeted cases for branches the random positions of rules.json and rounds.json
/// reach only rarely:
///  - throws whose beatable components tie on size and strength (equal trump-rank cards, where the
///    forced component is picked by display order), with odd leader seats and short hand lists;
///  - follows to leads of several tractors (the requirement walk's choices, and which required
///    tractor `mustPlayTractor` names when only some are played);
///  - tricks where a plain-suit lead (often a throw) is ruffed by several players (over-ruffs,
///    ruffs with the wrong structure, plays that match the lead in more than one way);
///  - every kind of kitty flip (a trump-rank card, a joker, either first, and the highest card
///    with ties), with and without a known dealer;
///  - the declaration text for every strength, suit and card variant.
/// Each list then goes on with `bigCount` cases at tables of 6 and 8 players (3 and 4 decks): texts of
/// declarations of three and four cards (named for the table's `players`), kitty flips of 6 and 8
/// cards, throws against 6 or 8 hands, follows to leads of sets and tractors of sets, and ruffs of
/// such leads by every other seat.
enum EdgeVectors {
    static func make(count: Int, bigCount: Int) -> [(String, JSON)] {
        var rand = Rand(0xED_6E5)
        var declarations = declarationTexts(rand: &rand)
        var flips = (0..<count).map { kittyFlip(kind: $0 % 5, rand: &rand) }
        var throwCases = (0..<count).map { throwCase(kind: $0 % 4, rand: &rand) }
        var follows = (0..<count).map { _ in followCase(rand: &rand) }
        var tricks = (0..<count).map { _ in trickCase(rand: &rand) }
        var big = Rand(0xB16_ED6E5)
        declarations += bigDeclarationTexts(rand: &big)
        flips += (0..<bigCount).map { bigKittyFlip(kind: $0 % 5, table: Cards.bigTables[$0 % 2], rand: &big) }
        throwCases += (0..<bigCount).map { bigThrowCase(kind: $0 % 3, table: Cards.bigTables[$0 % 2], rand: &big) }
        follows += (0..<bigCount).map { setFollowCase(decks: Cards.bigTables[$0 % 2].decks, rand: &big) }
        tricks += (0..<bigCount).map { bigTrickCase(table: Cards.bigTables[$0 % 2], rand: &big) }
        return [
            ("format", .int(1)),
            ("about", .string("Generated by ShengjiVectors from the Swift engine. Do not edit.")),
            ("declarations", .array(declarations)),
            ("kittyFlips", .array(flips)),
            ("throws", .array(throwCases)),
            ("follows", .array(follows)),
            ("tricks", .array(tricks)),
        ]
    }

    // MARK: Declaration text

    /// `Declaration.description` for every strength (including invalid ones), suit and card
    /// variant (none, one rank card, two rank cards, joker pairs), from every seat and two
    /// out-of-range ones.
    static func declarationTexts(rand: inout Rand) -> [JSON] {
        var out: [JSON] = []
        let players = [-1, 0, 1, 2, 3, 4, 5]
        var index = 0
        for strength in 0...5 {
            for suit in [nil] + Suit.allCases.map({ Optional($0) }) {
                let rank = Rank.allCases[rand.below(Rank.allCases.count)]
                let shown = suit ?? Suit.allCases[rand.below(4)]
                let variants: [[Card]] = [
                    [],
                    [Card(rank, shown, copy: rand.below(2))],
                    [Card(rank, shown), Card(rank, shown, copy: 1)],
                    [.smallJoker(), .smallJoker(copy: 1)],
                    [.bigJoker(copy: 1), .bigJoker()],
                ]
                for cards in variants {
                    let player = players[index % players.count]
                    index += 1
                    let declaration = Declaration(player: player, cards: cards, suit: suit, strength: strength)
                    out.append(.object([
                        ("declaration", json(declaration)),
                        ("description", .string(declaration.description)),
                    ]))
                }
            }
        }
        return out
    }

    // MARK: Kitty flips

    /// Nobody declares; `finishDealing` flips the kitty. The deck is every other card in id order,
    /// then the kitty (so only the kitty needs recording).
    static func kittyFlip(kind: Int, rand: inout Rand) -> JSON {
        let rank = Rank.allCases[rand.below(Rank.allCases.count)]
        let dealer: Int? = rand.percent(30) ? nil : rand.below(4)
        let rankCards = Cards.all.filter { $0.rank == rank }
        let jokers = Cards.all.filter { $0.isJoker }
        let plain = Cards.all.filter { !$0.isJoker && $0.rank != rank }
        var kitty: [Card]
        switch kind {
        case 0:
            kitty = rand.sample(Cards.all, 8)
        case 1:
            // No trump-rank card and no joker: the suit of the highest card.
            kitty = rand.sample(plain, 8)
        case 2:
            // Several cards share the highest rank: the first of them decides.
            let tops = Rank.allCases.filter { $0 != rank && $0.rawValue >= 5 }
            let top = tops[rand.below(tops.count)]
            let tied = rand.sample(plain.filter { $0.rank == top }, rand.between(2, 4))
            let lower = rand.sample(plain.filter { ($0.rank?.rawValue ?? 99) < top.rawValue }, 8 - tied.count)
            kitty = rand.shuffled(tied + lower)
        case 3:
            // A joker and a trump-rank card: whichever comes first decides.
            kitty = rand.shuffled(rand.sample(plain, 6) + rand.sample(jokers, 1) + rand.sample(rankCards, 1))
        default:
            // The only trump-rank card (or joker) comes late.
            let special = rand.percent(50) ? rand.sample(rankCards, 1) : rand.sample(jokers, 1)
            var cards = rand.sample(plain, 7)
            cards.insert(special[0], at: rand.between(4, 7))
            kitty = cards
        }
        let rest = Cards.all.filter { !kitty.contains($0) }
        var round = Round(trumpRank: rank, dealer: dealer, deck: rest + kitty)
        round.dealAll()
        round.finishDealing()
        return .object([
            ("trumpRank", json(rank)),
            ("dealer", json(dealer)),
            ("kitty", json(kitty)),
            ("phase", .string(round.phase.rawValue)),
            ("trump", json(round.trump)),
            ("trumpFromKitty", json(round.trumpFromKitty)),
            ("dealerAfter", json(round.dealer)),
            ("leader", .int(round.leader)),
        ])
    }

    // MARK: Throws

    static func throwCase(kind: Int, rand: inout Rand) -> JSON {
        // Equal-strength cases are drawn again (a bounded number of times) until two or more of the
        // beatable components tie on size and strength, so the display-order tie-break decides.
        var deal = throwDeal(kind: kind, rand: &rand)
        var attempts = 0
        while kind <= 1 && attempts < 40 && !hasForcedTie(deal) {
            deal = throwDeal(kind: kind, rand: &rand)
            attempts += 1
        }
        let (trump, leader, hands, cards) = deal

        // Odd seats and short hand lists: the leader is taken modulo 4, missing hands are skipped.
        var seatArgument = leader
        var handList = hands
        if rand.percent(20) {
            seatArgument = leader + 4 * [-2, -1, 1, 2][rand.below(4)]
        }
        if rand.percent(10) {
            handList = Array(hands.prefix(rand.between(1, 3)))
        }
        let others = (0..<handList.count).filter { $0 != ((seatArgument % 4) + 4) % 4 }.flatMap { handList[$0] }
        let poolCards = rand.sample(others, rand.between(0, others.count))
        return .object([
            ("trump", json(trump)),
            ("leader", .int(seatArgument)),
            ("hands", json(handList)),
            ("cards", json(cards)),
            ("isThrow", .bool(Rules.isThrow(cards, trump: trump))),
            ("check", json(Rules.checkThrow(cards, leader: seatArgument, hands: handList, trump: trump))),
            ("pool", json(poolCards)),
            ("poolCheck", json(Rules.checkThrow(cards, against: poolCards, trump: trump))),
        ])
    }

    /// True if the throw fails and another beatable component has the forced one's size and strength.
    static func hasForcedTie(_ deal: (Trump, Int, [[Card]], [Card])) -> Bool {
        let (trump, leader, hands, cards) = deal
        guard case let .fails(forced, _) = Rules.checkThrow(cards, leader: leader, hands: hands, trump: trump) else {
            return false
        }
        let opponents = (1..<4).map { hands[(leader + $0) % 4] }
        let ties = Combos.decompose(cards, trump: trump).filter { component in
            component.shape.cardCount == forced.shape.cardCount && component.topStrength == forced.topStrength
                && opponents.contains { Plays.canBeat(component, with: $0, trump: trump) }
        }
        return ties.count >= 2
    }

    /// Trump, leader, four hands and the leader's throw for one of the throw kinds.
    static func throwDeal(kind: Int, rand: inout Rand) -> (Trump, Int, [[Card]], [Card]) {
        var trump = Cards.randomTrump(&rand, noTrumpPercent: 25)
        var pool = CardPool()
        var hands: [[Card]] = [[], [], [], []]
        let leader = rand.below(4)
        let group: SuitGroup
        switch kind {
        case 0, 1:
            // Equal trump-rank cards (off-suit rank cards, or every rank card with no trump suit),
            // often several of them as singles and pairs, against stronger trumps.
            if kind == 1 { trump.suit = Suit.allCases[rand.below(4)] }
            group = .trump
            let equal = Suit.allCases.filter { $0 != trump.suit }.map { Face.regular($0, trump.rank) }
            hands[leader] = pool.takeFaces(equal, count: rand.between(2, 6), pairPercent: 35, rand: &rand)
            if rand.percent(50) {
                // Other trumps as pairs, so the equal singles stay the smallest beatable components.
                hands[leader] += pool.takeFaces(Cards.faces(in: .trump, trump: trump), count: rand.between(2, 4),
                                                pairPercent: 100, rand: &rand)
            }
            for seat in 0..<4 where seat != leader {
                let top = rand.percent(60)
                hands[seat] = pool.takeFaces(top ? Cards.topTrumpFaces(trump) : equal, count: rand.between(0, 4),
                                             pairPercent: top ? 30 : 50, rand: &rand)
            }
        case 2:
            // A plain suit: components beatable by different opponents (which one blocks).
            let suits = Suit.allCases.filter { $0 != trump.suit }
            let suit = suits[rand.below(suits.count)]
            group = .plain(suit)
            let faces = Cards.faces(in: group, trump: trump)
            hands[leader] = pool.takeFaces(faces, count: rand.between(3, 9), pairPercent: 60, rand: &rand)
            for seat in 0..<4 where seat != leader {
                hands[seat] = pool.takeFaces(faces, count: rand.between(0, 5), pairPercent: 60, rand: &rand)
            }
        default:
            // Several tractors of trumps on both sides.
            trump.suit = Suit.allCases[rand.below(4)]
            group = .trump
            let faces = Cards.faces(in: .trump, trump: trump)
            hands[leader] = pool.takeFaces(faces, count: rand.between(8, 16), pairPercent: 100, rand: &rand)
            for seat in 0..<4 where seat != leader {
                hands[seat] = pool.takeFaces(faces, count: rand.between(0, 8), pairPercent: 90, rand: &rand)
            }
        }
        // Fill every hand with other cards to a common size.
        let size = min(25, (hands.map(\.count).max() ?? 0) + rand.between(0, 4))
        var filler = rand.shuffled(pool.remaining { trump.group($0) != group })
        for seat in 0..<4 {
            while hands[seat].count < size, let card = filler.popLast() { hands[seat].append(card) }
            hands[seat] = rand.shuffled(hands[seat])
        }

        // The throw: whole components of the leader's group, at least two when possible.
        let own = Combos.cards(hands[leader], in: group, trump: trump)
        let components = Combos.decompose(own, trump: trump)
        var cards: [Card]
        if components.count >= 2 && rand.percent(70) {
            cards = rand.shuffled(rand.sample(components, rand.between(2, components.count)).flatMap(\.cards))
        } else {
            cards = rand.shuffled(own)
        }
        if cards.isEmpty { cards = [hands[leader][0]] }
        return (trump, leader, hands, cards)
    }

    // MARK: Follows to leads of several tractors

    /// A tractor of `length` pairs of `group` taken from `pool`, at random, or nil.
    static func takeTractor(length: Int, group: SuitGroup, trump: Trump, pool: inout CardPool,
                            rand: inout Rand) -> [Card]? {
        let available = pool.remaining { trump.group($0) == group }
        guard let tractor = rand.pick(Combos.tractors(in: available, length: length, trump: trump)) else {
            return nil
        }
        for card in tractor { _ = pool.take(card) }
        return tractor
    }

    static func followCase(rand: inout Rand) -> JSON {
        var trump = Cards.randomTrump(&rand, noTrumpPercent: 15)
        let isTrumpLead = rand.percent(55)
        if isTrumpLead && trump.suit == nil && rand.percent(70) { trump.suit = Suit.allCases[rand.below(4)] }
        let suits = Suit.allCases.filter { $0 != trump.suit }
        let group: SuitGroup = isTrumpLead ? .trump : .plain(suits[rand.below(suits.count)])
        var pool = CardPool()

        // The lead: two or three tractors (2...4 pairs; fewer in a plain suit), maybe a pair and a single.
        let maxPairs = isTrumpLead ? 7 : 4
        var lead: [Card] = []
        var pairsUsed = 0
        for _ in 0..<rand.between(2, 3) {
            let length = rand.between(2, isTrumpLead ? 4 : 2)
            guard pairsUsed + length <= maxPairs,
                  let tractor = takeTractor(length: length, group: group, trump: trump, pool: &pool, rand: &rand)
            else { continue }
            lead += tractor
            pairsUsed += length
        }
        if rand.percent(40) {
            lead += pool.takeFaces(Cards.faces(in: group, trump: trump), count: 2, pairPercent: 100, rand: &rand)
        }
        if rand.percent(40) {
            lead += pool.takeFaces(Cards.faces(in: group, trump: trump), count: 1, pairPercent: 0, rand: &rand)
        }
        if lead.isEmpty {
            lead = pool.takeFaces(Cards.faces(in: group, trump: trump), count: 4, pairPercent: 100, rand: &rand)
        }
        lead = rand.shuffled(lead)

        // The follower: pair-rich in the led group (often with shorter runs than the lead's
        // tractors), sometimes short of it.
        let groupLeft = pool.remaining { trump.group($0) == group }.count
        let wanted = rand.percent(80) ? lead.count + rand.between(0, 6) : rand.between(1, max(1, lead.count - 1))
        var hand = pool.takeFaces(Cards.faces(in: group, trump: trump), count: min(groupLeft, wanted),
                                  pairPercent: rand.between(70, 100), rand: &rand)
        let size = min(25, max(lead.count, hand.count + rand.between(0, 5)))
        var filler = rand.shuffled(pool.remaining { trump.group($0) != group })
        while hand.count < size, let card = filler.popLast() { hand.append(card) }
        hand = rand.shuffled(hand)

        let held = Combos.cards(hand, in: group, trump: trump)
        let requirement = Rules.followRequirement(lead: lead, suitCards: held, trump: trump)
        var plays: [[Card]] = [Plays.legalFollow(hand: hand, lead: lead, trump: trump, rand: &rand)]
        let elsewhere = filler
        plays += Plays.randomAttempts(hand: hand, lead: lead, trump: trump, elsewhere: elsewhere, rand: &rand)
        if held.count >= lead.count {
            // Only some of the required tractors (each subset in turn), the rest single cards first.
            let lengths = requirement.tractorLengths
            if !lengths.isEmpty {
                for skip in 0..<lengths.count {
                    var kept = lengths
                    kept.remove(at: skip)
                    guard let tractors = Plays.disjointTractors(in: held, lengths: kept, trump: trump, rand: &rand)
                    else { continue }
                    var rest = held
                    var play: [Card] = []
                    for tractor in tractors {
                        play += tractor
                        rest.remove(cards: tractor)
                    }
                    let singles = Combos.components(of: .single, in: rest, trump: trump).map { $0.cards[0] }
                    let others = rest.filter { !singles.contains($0) }
                    play += Array((rand.shuffled(singles) + rand.shuffled(others)).prefix(lead.count - play.count))
                    if play.count == lead.count { plays.append(rand.shuffled(play)) }
                }
            }
            // The required structure with one pair broken.
            let legal = plays[0]
            if let pair = Combos.pairs(in: legal, trump: trump).first,
               let spare = held.first(where: { !legal.contains($0) && $0.face != pair[0].face }) {
                var broken = legal
                broken.remove(cards: [pair[1]])
                broken.append(spare)
                plays.append(broken)
            }
        }

        return .object([
            ("trump", json(trump)),
            ("lead", json(lead)),
            ("hand", json(hand)),
            ("requirement", json(requirement)),
            ("plays", .array(plays.map { cards in
                var fields: [(String, JSON)] = [
                    ("cards", json(cards)),
                    ("matches", .bool(Rules.matchesStructure(cards, lead: lead, trump: trump))),
                ]
                if let violation = Rules.validateFollow(cards, hand: hand, lead: lead, trump: trump) {
                    fields.append(("violation", json(violation)))
                    fields.append(("explanation", .string(violation.explanation)))
                }
                return .object(fields)
            })),
        ])
    }

    // MARK: Ruffed tricks

    /// A component of `shape` from the pool's cards of `group`, at random, taken from the pool.
    static func takeShape(_ shape: ComboShape, group: SuitGroup, trump: Trump, pool: inout CardPool,
                          rand: inout Rand) -> [Card]? {
        let available = pool.remaining { trump.group($0) == group }
        guard let component = rand.pick(Combos.components(of: shape, in: available, trump: trump)) else { return nil }
        for card in component.cards { _ = pool.take(card) }
        return component.cards
    }

    static func trickCase(rand: inout Rand) -> JSON {
        let trump = Cards.randomTrump(&rand, noTrumpPercent: 20)
        let suits = Suit.allCases.filter { $0 != trump.suit }
        let suit = suits[rand.below(suits.count)]
        let ledGroup = SuitGroup.plain(suit)
        var pool = CardPool()
        let leader = rand.below(4)
        var lead = pool.takeFaces(Cards.faces(in: ledGroup, trump: trump), count: rand.between(2, 8),
                                  pairPercent: 70, rand: &rand)
        if rand.percent(30), let tractor = takeTractor(length: 2, group: ledGroup, trump: trump, pool: &pool,
                                                         rand: &rand) {
            lead += tractor
        }
        lead = rand.shuffled(lead)
        let shapes = Combos.decompose(lead, trump: trump).map(\.shape)
        var plays = [Play(player: leader, cards: lead)]
        for step in 1..<4 {
            let seat = (leader + step) % 4
            var cards: [Card] = []
            switch rand.below(6) {
            case 0, 1, 2:
                // A ruff with the lead's exact shapes, when the pool still allows it.
                for shape in shapes {
                    guard let part = takeShape(shape, group: .trump, trump: trump, pool: &pool, rand: &rand) else { break }
                    cards += part
                }
            case 3:
                // Trumps with any structure (often not the lead's).
                cards = pool.takeFaces(Cards.faces(in: .trump, trump: trump), count: lead.count,
                                       pairPercent: rand.between(0, 90), rand: &rand)
            case 4:
                // The led suit, pair-rich.
                cards = pool.takeFaces(Cards.faces(in: ledGroup, trump: trump), count: lead.count, pairPercent: 80,
                                       rand: &rand)
            default:
                break
            }
            // Short of cards: fill with anything (a discard, or a mixed play).
            let missing = lead.count - cards.count
            if missing > 0 {
                let extra = rand.sample(pool.remaining(), missing)
                for card in extra { _ = pool.take(card) }
                cards += extra
            }
            plays.append(Play(player: seat, cards: rand.shuffled(Array(cards.prefix(lead.count)))))
        }
        return .object([
            ("trump", json(trump)),
            ("plays", .array(plays.map { json($0) })),
            ("winners", .array((1...plays.count).map { .int(Rules.winningIndex(Array(plays.prefix($0)), trump: trump)) })),
        ])
    }

    // MARK: Bigger tables

    /// `Declaration.description(players:)` for strengths 5...11 (three and four cards, and beyond),
    /// every suit and card variant, from every seat of 6 and 8-player tables and two outside them.
    static func bigDeclarationTexts(rand: inout Rand) -> [JSON] {
        var out: [JSON] = []
        var index = 0
        for strength in 5...11 {
            for suit in [nil] + Suit.allCases.map({ Optional($0) }) {
                let rank = Rank.allCases[rand.below(Rank.allCases.count)]
                let shown = suit ?? Suit.allCases[rand.below(4)]
                let variants: [[Card]] = [
                    [],
                    (0..<3).map { Card(rank, shown, copy: $0) },
                    (0..<4).map { Card(rank, shown, copy: 3 - $0) },
                    [.smallJoker(copy: 2), .smallJoker(), .smallJoker(copy: 1)],
                    (0..<4).map { Card.bigJoker(copy: $0) },
                ]
                for cards in variants {
                    let table = Cards.bigTables[index % 2]
                    let player = (index / 2) % (table.players + 2) - 1
                    index += 1
                    let declaration = Declaration(player: player, cards: cards, suit: suit, strength: strength)
                    out.append(.object([
                        ("players", .int(table.players)),
                        ("declaration", json(declaration)),
                        ("description", .string(declaration.description(players: table.players))),
                    ]))
                }
            }
        }
        return out
    }

    /// Nobody declares at a bigger table; `finishDealing` flips its kitty of 6 or 8 cards.
    static func bigKittyFlip(kind: Int, table: TableSize, rand: inout Rand) -> JSON {
        let size = table.kittySize
        let all = Cards.deck(table.decks)
        let rank = Rank.allCases[rand.below(Rank.allCases.count)]
        let dealer: Int? = rand.percent(30) ? nil : rand.below(table.players)
        let rankCards = all.filter { $0.rank == rank }
        let jokers = all.filter { $0.isJoker }
        let plain = all.filter { !$0.isJoker && $0.rank != rank }
        var kitty: [Card]
        switch kind {
        case 0:
            kitty = rand.sample(all, size)
        case 1:
            kitty = rand.sample(plain, size)
        case 2:
            // Several cards share the highest rank (copies of one card among them).
            let tops = Rank.allCases.filter { $0 != rank && $0.rawValue >= 5 }
            let top = tops[rand.below(tops.count)]
            let tied = rand.sample(plain.filter { $0.rank == top }, rand.between(2, 4))
            let lower = rand.sample(plain.filter { ($0.rank?.rawValue ?? 99) < top.rawValue }, size - tied.count)
            kitty = rand.shuffled(tied + lower)
        case 3:
            kitty = rand.shuffled(rand.sample(plain, size - 2) + rand.sample(jokers, 1) + rand.sample(rankCards, 1))
        default:
            let special = rand.percent(50) ? rand.sample(rankCards, 1) : rand.sample(jokers, 1)
            var cards = rand.sample(plain, size - 1)
            cards.insert(special[0], at: rand.between(size / 2, size - 1))
            kitty = cards
        }
        let rest = all.filter { !kitty.contains($0) }
        var round = Round(trumpRank: rank, dealer: dealer, deck: rest + kitty, table: table)
        round.dealAll()
        round.finishDealing()
        return .object([
            ("players", .int(table.players)),
            ("trumpRank", json(rank)),
            ("dealer", json(dealer)),
            ("kitty", json(kitty)),
            ("phase", .string(round.phase.rawValue)),
            ("trump", json(round.trump)),
            ("trumpFromKitty", json(round.trumpFromKitty)),
            ("dealerAfter", json(round.dealer)),
            ("leader", .int(round.leader)),
        ])
    }

    /// A throw at a bigger table against `players` hands: sets of trumps on both sides, a plain suit
    /// of sets and singles, or tractors of sets. Odd leader seats and short hand lists too.
    static func bigThrowCase(kind: Int, table: TableSize, rand: inout Rand) -> JSON {
        let n = table.players
        var trump = Cards.randomTrump(&rand, noTrumpPercent: 20)
        var pool = CardPool(decks: table.decks)
        var hands = [[Card]](repeating: [], count: n)
        let leader = rand.below(n)
        let group: SuitGroup
        switch kind {
        case 0:
            // Sets of trumps near the top on both sides (equal rank cards, jokers).
            trump.suit = Suit.allCases[rand.below(4)]
            group = .trump
            hands[leader] = pool.takeCopies(Cards.topTrumpFaces(trump), count: rand.between(4, 12), multiPercent: 80,
                                            rand: &rand)
            for seat in 0..<n where seat != leader {
                hands[seat] = pool.takeCopies(Cards.faces(in: .trump, trump: trump), count: rand.between(0, 6),
                                              multiPercent: 60, rand: &rand)
            }
        case 1:
            // A plain suit: sets, pairs and singles beatable by different players.
            let suits = Suit.allCases.filter { $0 != trump.suit }
            let suit = suits[rand.below(suits.count)]
            group = .plain(suit)
            let faces = Cards.faces(in: group, trump: trump)
            hands[leader] = pool.takeCopies(faces, count: rand.between(4, 12), multiPercent: 70, rand: &rand)
            for seat in 0..<n where seat != leader {
                hands[seat] = pool.takeCopies(faces, count: rand.between(0, 5), multiPercent: 60, rand: &rand)
            }
        default:
            // Tractors of sets of trumps on both sides.
            trump.suit = Suit.allCases[rand.below(4)]
            group = .trump
            let faces = Cards.faces(in: .trump, trump: trump)
            hands[leader] = pool.takeCopies(faces, count: rand.between(9, 20), multiPercent: 100, rand: &rand)
            for seat in 0..<n where seat != leader {
                hands[seat] = pool.takeCopies(faces, count: rand.between(0, 8), multiPercent: 90, rand: &rand)
            }
        }
        let size = min(table.handSize, (hands.map(\.count).max() ?? 0) + rand.between(0, 4))
        var filler = rand.shuffled(pool.remaining { trump.group($0) != group })
        for seat in 0..<n {
            while hands[seat].count < size, let card = filler.popLast() { hands[seat].append(card) }
            hands[seat] = rand.shuffled(hands[seat])
        }
        let own = Combos.cards(hands[leader], in: group, trump: trump)
        let components = Combos.decompose(own, trump: trump)
        var cards: [Card]
        if components.count >= 2 && rand.percent(70) {
            cards = rand.shuffled(rand.sample(components, rand.between(2, components.count)).flatMap(\.cards))
        } else {
            cards = rand.shuffled(own)
        }
        if cards.isEmpty { cards = [hands[leader][0]] }

        // Odd seats and short hand lists: with fewer hands than 4 the leader is taken modulo 4.
        var seatArgument = leader
        var handList = hands
        if rand.percent(20) { seatArgument = leader + n * [-2, -1, 1, 2][rand.below(4)] }
        if rand.percent(10) { handList = Array(hands.prefix(rand.between(1, n - 1))) }
        let seats = max(4, handList.count)
        let leaderSeat = ((seatArgument % seats) + seats) % seats
        let others = (0..<handList.count).filter { $0 != leaderSeat }.flatMap { handList[$0] }
        let poolCards = rand.sample(others, rand.between(0, min(others.count, 60)))
        return .object([
            ("players", .int(n)),
            ("trump", json(trump)),
            ("leader", .int(seatArgument)),
            ("hands", json(handList)),
            ("cards", json(cards)),
            ("isThrow", .bool(Rules.isThrow(cards, trump: trump))),
            ("check", json(Rules.checkThrow(cards, leader: seatArgument, hands: handList, trump: trump))),
            ("pool", json(poolCards)),
            ("poolCheck", json(Rules.checkThrow(cards, against: poolCards, trump: trump))),
        ])
    }

    /// A component of `shape` from the pool's cards of `group`, at random, taken from the pool.
    static func takeUnit(_ shape: ComboShape, group: SuitGroup, trump: Trump, pool: inout CardPool,
                         rand: inout Rand) -> [Card]? {
        let available = pool.remaining { trump.group($0) == group }
        guard let unit = rand.pick(Combos.units(of: shape, in: available, trump: trump)) else { return nil }
        for card in unit { _ = pool.take(card) }
        return unit
    }

    /// A follow to a lead of sets and tractors of sets (3 or 4 decks): the requirement walk over
    /// sets of any width, which unit `mustPlaySets` and `mustPlaySetTractor` name, and the keys.
    static func setFollowCase(decks: Int, rand: inout Rand) -> JSON {
        var trump = Cards.randomTrump(&rand, noTrumpPercent: 15)
        let isTrumpLead = rand.percent(55)
        if isTrumpLead && trump.suit == nil && rand.percent(70) { trump.suit = Suit.allCases[rand.below(4)] }
        let suits = Suit.allCases.filter { $0 != trump.suit }
        let group: SuitGroup = isTrumpLead ? .trump : .plain(suits[rand.below(suits.count)])
        var pool = CardPool(decks: decks)

        // The lead: one to three of tractors of sets, sets, tractors of pairs, then maybe a pair and a single.
        var shapes: [ComboShape] = [.setTractor(width: 3, length: 2), .set(3), .tractor(2), .pair]
        if decks == 4 { shapes += [.set(4), .setTractor(width: 4, length: 2)] }
        if isTrumpLead { shapes += [.setTractor(width: 3, length: 3), .tractor(3)] }
        var lead: [Card] = []
        for _ in 0..<rand.between(1, 3) {
            guard let shape = rand.pick(shapes), lead.count + shape.cardCount <= 16,
                  let unit = takeUnit(shape, group: group, trump: trump, pool: &pool, rand: &rand) else { continue }
            lead += unit
        }
        if rand.percent(40) {
            lead += pool.takeCopies(Cards.faces(in: group, trump: trump), count: 2, multiPercent: 100, rand: &rand)
        }
        if rand.percent(40) {
            lead += pool.takeCopies(Cards.faces(in: group, trump: trump), count: 1, multiPercent: 0, rand: &rand)
        }
        if lead.isEmpty {
            lead = pool.takeCopies(Cards.faces(in: group, trump: trump), count: 3, multiPercent: 100, rand: &rand)
        }
        lead = rand.shuffled(lead)

        // The follower: rich in sets of the led group (often narrower or shorter than the lead's).
        let groupLeft = pool.remaining { trump.group($0) == group }.count
        let wanted = rand.percent(80) ? lead.count + rand.between(0, 8) : rand.between(1, max(1, lead.count - 1))
        var hand = pool.takeCopies(Cards.faces(in: group, trump: trump), count: min(groupLeft, wanted),
                                   multiPercent: rand.between(60, 100), rand: &rand)
        // At most a dealer's hand of 34 cards (26 and the kitty of 8).
        let size = min(34, max(lead.count, hand.count + rand.between(0, 5)))
        var filler = rand.shuffled(pool.remaining { trump.group($0) != group })
        while hand.count < size, let card = filler.popLast() { hand.append(card) }
        hand = rand.shuffled(hand)

        let held = Combos.cards(hand, in: group, trump: trump)
        let requirement = Rules.followRequirement(lead: lead, suitCards: held, trump: trump)
        let legal = Plays.legalFollow(hand: hand, lead: lead, trump: trump, rand: &rand)
        var plays: [[Card]] = [legal]
        plays += Plays.setAttempts(hand: hand, lead: lead, trump: trump, legal: legal, rand: &rand)
        plays += Plays.randomAttempts(hand: hand, lead: lead, trump: trump, elsewhere: filler, rand: &rand)
        // Set-rich plays of the led group drawn from the pool (structure and keys, not legality).
        for _ in 0..<2 {
            var probe = pool
            let cards = probe.takeCopies(Cards.faces(in: group, trump: trump), count: lead.count, multiPercent: 85,
                                         rand: &rand)
            if cards.count == lead.count { plays.append(rand.shuffled(cards)) }
        }

        return .object([
            ("decks", .int(decks)),
            ("trump", json(trump)),
            ("lead", json(lead)),
            ("hand", json(hand)),
            ("requirement", json(requirement)),
            ("plays", .array(plays.map { cards in
                var fields: [(String, JSON)] = [
                    ("cards", json(cards)),
                    ("matches", .bool(Rules.matchesStructure(cards, lead: lead, trump: trump))),
                ]
                if let violation = Rules.validateFollow(cards, hand: hand, lead: lead, trump: trump) {
                    fields.append(("violation", json(violation)))
                    fields.append(("explanation", .string(violation.explanation)))
                }
                return .object(fields)
            })),
        ])
    }

    /// A plain-suit lead with sets (often a throw) at a bigger table, ruffed and over-ruffed by the
    /// other `players - 1` seats with trumps of the lead's shapes, any trumps, the led suit or a discard.
    static func bigTrickCase(table: TableSize, rand: inout Rand) -> JSON {
        let n = table.players
        let trump = Cards.randomTrump(&rand, noTrumpPercent: 20)
        let suits = Suit.allCases.filter { $0 != trump.suit }
        let suit = suits[rand.below(suits.count)]
        let ledGroup = SuitGroup.plain(suit)
        var pool = CardPool(decks: table.decks)
        let leader = rand.below(n)
        var lead = pool.takeCopies(Cards.faces(in: ledGroup, trump: trump), count: rand.between(2, 9), multiPercent: 75,
                                   rand: &rand)
        if rand.percent(30), let tractor = takeUnit(.setTractor(width: 3, length: 2), group: ledGroup, trump: trump,
                                                      pool: &pool, rand: &rand) {
            lead += tractor
        }
        lead = rand.shuffled(lead)
        let shapes = Combos.decompose(lead, trump: trump).map(\.shape)
        var plays = [Play(player: leader, cards: lead)]
        for step in 1..<n {
            let seat = (leader + step) % n
            var cards: [Card] = []
            switch rand.below(6) {
            case 0, 1, 2:
                for shape in shapes {
                    guard let part = takeUnit(shape, group: .trump, trump: trump, pool: &pool, rand: &rand) else { break }
                    cards += part
                }
            case 3:
                cards = pool.takeCopies(Cards.faces(in: .trump, trump: trump), count: lead.count,
                                        multiPercent: rand.between(0, 90), rand: &rand)
            case 4:
                cards = pool.takeCopies(Cards.faces(in: ledGroup, trump: trump), count: lead.count, multiPercent: 80,
                                        rand: &rand)
            default:
                break
            }
            let missing = lead.count - cards.count
            if missing > 0 {
                let extra = rand.sample(pool.remaining(), missing)
                for card in extra { _ = pool.take(card) }
                cards += extra
            }
            plays.append(Play(player: seat, cards: rand.shuffled(Array(cards.prefix(lead.count)))))
        }
        return .object([
            ("players", .int(n)),
            ("trump", json(trump)),
            ("plays", .array(plays.map { json($0) })),
            ("winners", .array((1...plays.count).map { .int(Rules.winningIndex(Array(plays.prefix($0)), trump: trump)) })),
        ])
    }
